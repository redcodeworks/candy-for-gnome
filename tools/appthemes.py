"""Shared by the per-application theme generators (tools/{alacritty,helix,yazi,kitty,bat,eza,zellij,claude}-gen.py). Not a program.

COLOUR SOURCES (one model for every tool, so the apps show what Ptyxis, Ghostty and the toolkit themes show):
  term  the 18 terminal colours exactly as tools/ghostty-gen.py has them (the Ptyxis built-in decision: Background = bg_deep, Foreground = fg, Color1..6
        the accents, Color0/7/8..15 from [<variant>.terminal]; a nudge is reverted because Ptyxis shows the built-in unchanged); used by the terminals
        (Alacritty, kitty) as they are.
  syn   the editor palette of tools/gtksourceview-gen.py (red orange yellow green cyan blue magenta purple fg-dim comment, each moved in LIGHTNESS only
        until it has 4.5:1 (comments 3:1) on bg_deep and on the current line; bg-deep, bg = the current line, fg, selection); used by every
        tool that draws text on the editor background: Helix, bat and Yazi's code preview, eza, Yazi, zellij and Claude Code.
  R     the scheme's own resolved roles (bg_deep, bg, surface, surface_high, fg, ...), for surfaces and borders.
A dark-only scheme has only the dark variant, a light-only one only the light variant (a dark theme labelled light would lie); the installer uses the
dark file for both appearances of a dark-only scheme, as Ghostty does.
"""
import sys, os, importlib.util
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)   # python3 -I does not add the script dir
import schemeroles as sr

def _load(fn, name):
    sp = importlib.util.spec_from_file_location(name, os.path.join(HERE, fn)); m = importlib.util.module_from_spec(sp); sp.loader.exec_module(m); return m
_gg = _load('ghostty-gen.py', 'ghostty_gen'); _gv = _load('gtksourceview-gen.py', 'gtksourceview_gen')
mix, contrast, nudge_to = sr.mix, sr.contrast, sr.nudge_to

class V:
    """One variant of a scheme: .slot ('dark'|'light'), .R roles, .term (terminal colours, upper-case hex), .syn (editor palette, lower-case hex)."""
    def __init__(self, S, roles, slot):
        self.slot = slot; self.R = roles[slot]; self.dark = slot == 'dark'
        self.term = {k: v.lower() for k, v in _gg.colors(S, roles, slot).items()}
        self.notes = []; self.syn = {k: v.lower() for k, v in _gv.palette(self.R, self.notes, slot).items()}
        self.sel = self.R['selection'].lower()
        self.title = S['title']
    def ink(self, color, bg=None, need=4.5):
        """`color` moved in lightness only until it has `need`:1 on `bg` (default: the editor background)."""
        return nudge_to(color, bg or self.syn['bg-deep'], need)[0]

def model(scheme_dir):
    """(scheme name, {slot: V}) for the slots the scheme has (dark first)."""
    S, roles, _ = sr.load(scheme_dir)
    scheme = os.path.basename(os.path.abspath(scheme_dir))
    return scheme, {s: V(S, roles, s) for s in ('dark', 'light') if s in roles}, S

def fit(bg, fg, toward, need=4.5):
    """`bg` moved towards `toward` in 5 % steps until `fg` has `need`:1 on it (unchanged when it already has)."""
    n, c = 0, bg
    while contrast(fg, c) < need and n < 20:
        n += 1; c = mix(bg, toward, 0.05 * n)
    return c

def ident(scheme, slot): return 'candy-for-gnome-%s-%s' % (scheme, slot)
def rgb3(c): return ' '.join(str(v) for v in sr.hx(c))

def main(build, subdir, doc):
    """CLI of a generator: <scheme-dir> [--check]; writes <scheme-dir>/<subdir>/..., removing stale files (a scheme that lost a variant leaves none)."""
    if len(sys.argv) < 2: sys.exit(doc)
    d = sys.argv[1].rstrip('/')
    scheme, files = build(d)
    if '--check' in sys.argv:
        for n, t in files.items(): print('== ' + n); print(t)
        return
    import shutil
    out = '%s/%s' % (d, subdir)
    shutil.rmtree(out, ignore_errors=True)
    for n, t in files.items():
        p = '%s/%s' % (out, n); os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'w') as f: f.write(t)
    print('wrote %d file(s) to %s' % (len(files), out))

def header(scheme, tool, v, comment='#'):
    """The first lines of a generated text file: the installer's marker and the provenance line."""
    return ['%s candy-for-gnome: %s' % (comment, scheme),
            '%s SPDX-License-Identifier: MIT. Generated by tools/%s-gen.py from %s/scheme.toml; do not edit.' % (comment, tool, scheme),
            '%s %s, %s variant.' % (comment, v.title, v.slot)]

def tmtheme(scheme, tool, v):
    """A TextMate/syntect .tmTheme (bat, and the code preview of a Yazi flavor) from the editor palette."""
    c = v.syn
    def rule(name, scope, fg=None, bg=None, style=None):
        s = ''.join('\n\t\t\t\t<key>%s</key>\n\t\t\t\t<string>%s</string>' % kv for kv in (('foreground', fg), ('background', bg), ('fontStyle', style)) if kv[1])
        return '\t\t<dict>\n\t\t\t<key>name</key>\n\t\t\t<string>%s</string>\n\t\t\t<key>scope</key>\n\t\t\t<string>%s</string>\n\t\t\t<key>settings</key>\n\t\t\t<dict>%s\n\t\t\t</dict>\n\t\t</dict>' % (name, scope, s)
    rules = [
        ('Comment', 'comment, punctuation.definition.comment', c['comment'], None, 'italic'),
        ('String', 'string', c['green']), ('Regexp', 'string.regexp', c['cyan']),
        ('Number', 'constant.numeric', c['orange']), ('Language constant', 'constant.language, support.constant', c['orange']),
        ('Character constant', 'constant.character, constant.other', c['cyan']), ('Escape', 'constant.character.escape', c['cyan']),
        ('Keyword', 'keyword, keyword.control', c['magenta']), ('Operator', 'keyword.operator', c['cyan']),
        ('Storage', 'storage, storage.type, storage.modifier', c['red']),
        ('Function', 'entity.name.function, support.function, meta.function-call', c['blue']),
        ('Type', 'entity.name.type, entity.name.class, entity.other.inherited-class, support.class, support.type', c['yellow']),
        ('Variable', 'variable', c['fg']), ('Parameter', 'variable.parameter', c['fg'], None, 'italic'),
        ('Builtin variable', 'variable.language', c['red'], None, 'italic'),
        ('Tag', 'entity.name.tag', c['red']), ('Attribute', 'entity.other.attribute-name', c['yellow']),
        ('Preprocessor', 'meta.preprocessor, entity.name.function.preprocessor', c['purple']),
        ('Punctuation', 'punctuation', c['fg-dim']),
        ('Invalid', 'invalid, invalid.illegal', c['bg-deep'], c['red']), ('Deprecated', 'invalid.deprecated', c['bg-deep'], c['yellow']),
        ('Heading', 'markup.heading, entity.name.section', c['yellow'], None, 'bold'),
        ('Bold', 'markup.bold', None, None, 'bold'), ('Italic', 'markup.italic', None, None, 'italic'),
        ('Link', 'markup.underline.link, string.other.link', c['blue'], None, 'underline'), ('Raw', 'markup.raw, markup.inline.raw', c['orange']),
        ('List marker', 'punctuation.definition.list, markup.list', c['cyan']),
        ('Diff inserted', 'markup.inserted, meta.diff.header.to-file', c['green']), ('Diff deleted', 'markup.deleted, meta.diff.header.from-file', c['red']),
        ('Diff changed', 'markup.changed', c['yellow']), ('Diff header', 'meta.diff.header, meta.diff.range', c['blue']),
    ]
    g = [('background', c['bg-deep']), ('foreground', c['fg']), ('caret', c['fg']), ('lineHighlight', c['bg']), ('selection', c['selection']),
         ('invisibles', c['comment']), ('gutter', c['bg-deep']), ('gutterForeground', c['fg-dim']), ('findHighlight', c['yellow']),
         ('findHighlightForeground', c['bg-deep']), ('guide', c['selection']), ('activeGuide', c['comment'])]
    L = ['<?xml version="1.0" encoding="UTF-8"?>',
         '<!-- candy-for-gnome: %s -->' % scheme,
         '<!-- SPDX-License-Identifier: MIT. Generated by tools/%s-gen.py from %s/scheme.toml; do not edit. -->' % (tool, scheme),
         '<!DOCTYPE plist PUBLIC "-//Apple Computer//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
         '<plist version="1.0">', '<dict>', '\t<key>name</key>', '\t<string>%s %s (candy-for-gnome)</string>' % (v.title, v.slot.capitalize()),
         '\t<key>settings</key>', '\t<array>', '\t\t<dict>\n\t\t\t<key>settings</key>\n\t\t\t<dict>' +
         ''.join('\n\t\t\t\t<key>%s</key>\n\t\t\t\t<string>%s</string>' % kv for kv in g) + '\n\t\t\t</dict>\n\t\t</dict>']
    L += [rule(*r) for r in rules]
    L += ['\t</array>', '</dict>', '</plist>']
    return '\n'.join(L) + '\n'
