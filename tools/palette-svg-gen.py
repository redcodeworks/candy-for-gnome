"""Generate a scheme's terminal palette pictures (<scheme>/palette-dark.svg, <scheme>/palette-light.svg) from its scheme.toml.

  python3 -I tools/palette-svg-gen.py <scheme-dir> [--check]     # --check: print the files' names and sizes, write nothing

Repository documentation only (the README gallery and the scheme folders): the installer never copies them, it copies only <scheme>/themes/<Name>/
and the per-tool files. A dark-only scheme has only palette-dark.svg, a light-only one only palette-light.svg (the same rule as the Ghostty files).

COLOURS: the single source of truth is `colors()` of tools/ghostty-gen.py, the function that builds the Ghostty theme (the data of the Ptyxis
built-in decision, nudges reverted), so a picture shows exactly the terminal theme and cannot drift from it. Background, Foreground, Color0..15.

LOOK: two rows of eight 96x64 squares (colours 0-7, then the bright 8-15) on a rectangle in the scheme's terminal background, 16 px padding, a 4 px
gap; the uppercase #RRGGBB centred (font-size 12), the index small in the top-left corner (9), text black or white, whichever has the higher WCAG
contrast on the square; a square nearly equal to the background (contrast under 1.3) gets a faint outline in the foreground colour; a caption with the
scheme title and variant in the foreground colour. Generic monospace font stack, no embedded font, no external reference. Deterministic.
"""
import sys, os, html, importlib.util
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)   # python3 -I does not add the script dir
import schemeroles as sr

FONT = 'ui-monospace, SFMono-Regular, Menlo, Consolas, monospace'
_sp = importlib.util.spec_from_file_location('ghostty_gen', os.path.join(HERE, 'ghostty-gen.py'))
gg = importlib.util.module_from_spec(_sp); _sp.loader.exec_module(gg)

def lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
def ratio(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)
def text_on(c): return '#000000' if ratio(c, '#000000') >= ratio(c, '#FFFFFF') else '#FFFFFF'

def svg(scheme, title, variant, c):
    bg, fg = c['Background'].upper(), c['Foreground'].upper()
    P, W, H, G = 16, 96, 64, 4
    w = P * 2 + 8 * W + 7 * G; cap = 22; h = P * 2 + 2 * H + G + cap
    cap_text = '%s (%s)' % (title, variant)
    o = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" role="img" font-family="%s">' % (w, h, w, h, FONT),
         '<title>%s: terminal palette</title>' % html.escape(cap_text),
         '<desc>Colors of the candy-for-gnome terminal theme %s-%s (generated by tools/palette-svg-gen.py from %s/scheme.toml).</desc>' % (scheme, variant, scheme),
         '<rect width="%d" height="%d" fill="%s"/>' % (w, h, bg)]
    for i in range(16):
        x = P + (i % 8) * (W + G); y = P + (i // 8) * (H + G); col = c['Color%d' % i].upper(); t = text_on(col)
        st = ' stroke="%s" stroke-opacity="0.35" stroke-width="1"' % fg if ratio(col, bg) < 1.3 else ''
        o.append('<rect x="%d" y="%d" width="%d" height="%d" fill="%s"%s/>' % (x, y, W, H, col, st))
        o.append('<text x="%d" y="%d" font-size="9" fill="%s">%d</text>' % (x + 4, y + 11, t, i))
        o.append('<text x="%g" y="%g" font-size="12" fill="%s" text-anchor="middle">%s</text>' % (x + W / 2, y + H / 2 + 4, t, col))
    o.append('<text x="%d" y="%d" font-size="11" fill="%s">%s</text>' % (P, h - P + 4, fg, html.escape(cap_text)))
    o.append('</svg>')
    return '\n'.join(o) + '\n'

def build(scheme_dir):
    S, roles, _ = sr.load(scheme_dir)
    scheme = os.path.basename(os.path.abspath(scheme_dir))
    return scheme, {'palette-%s.svg' % v: svg(scheme, S['title'], v, gg.colors(S, roles, v)) for v in ('dark', 'light') if v in roles}

def main():
    if len(sys.argv) < 2: sys.exit(__doc__)
    d = sys.argv[1].rstrip('/')
    scheme, files = build(d)
    if '--check' in sys.argv:
        for n, t in files.items(): print('%s/%s %d bytes' % (d, n, len(t)))
        return
    for f in ('palette-dark.svg', 'palette-light.svg'):
        if f not in files and os.path.exists(os.path.join(d, f)): os.remove(os.path.join(d, f))   # a scheme that lost a variant leaves no stale file
    for n, t in files.items():
        with open('%s/%s' % (d, n), 'w') as f: f.write(t)
        print('wrote %s/%s' % (d, n))

if __name__ == '__main__': main()
