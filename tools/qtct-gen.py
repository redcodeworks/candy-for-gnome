"""Generate a scheme's qt5ct/qt6ct palettes (<scheme>/qtct/candy-for-gnome-<scheme>-{dark,light}.conf).

  python3 -I tools/qtct-gen.py <scheme-dir> [--check]     # --check: print, write nothing

A qtct [ColorScheme] file: active_colors, disabled_colors and inactive_colors, 22 `#rrggbb` values in QPalette order (windowText, button, light, midlight,
dark, mid, text, brightText, buttonText, base, window, shadow, highlight, highlightedText, link, linkVisited, alternateBase, the unused slot, toolTipBase,
toolTipText, placeholderText, accent). The roles are the ones of tools/kde-gen.py (tools/appthemes.py qt_roles): base = the editor background, window =
bg, button = surface_high (moved until the text has 4.5:1), highlight = the default accent with its GTK ink. light/midlight/dark/mid are the button
colour mixed towards white or black (30, 15, 45, 25 percent), shadow is black, brightText white. Disabled: text colours halfway to the window colour,
highlight = surface_high; inactive = active. A dark-only scheme has only the dark file, a light-only one only the light file. The installer applies the
accent a user picked (the default accent's hex is replaced). Marker: the first line `# candy-for-gnome: <scheme>`.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import appthemes as A

def palette(r, off=False):
    m = A.mix; b = r['button']
    text = m(r['text'], r['window'], 0.5) if off else r['text']
    hi, hfg = (r['alt_window'], text) if off else (r['accent'], r['accent_fg'])
    v = [text, b, m(b, '#ffffff', 0.30), m(b, '#ffffff', 0.15), m(b, '#000000', 0.45), m(b, '#000000', 0.25), text, '#ffffff', text, r['view'], r['window'], '#000000',
         hi, hfg, r['link'], r['visited'], r['alt_view'], r['alt_window'], r['tip'], r['text'], r['dim'], r['accent']]
    return ', '.join(x.lower() for x in v)

def build(d):
    scheme, vs, S = A.model(d)
    out = {}
    if not A.in_qt_scope(scheme): return scheme, out    # pilot: featured schemes only (A.QT_SCOPE)
    for s, v in vs.items():
        r = A.qt_roles(S, v)
        out[A.ident(scheme, s) + '.conf'] = '\n'.join(['# candy-for-gnome: %s' % scheme,
            '# SPDX-License-Identifier: MIT. Generated by tools/qtct-gen.py from %s/scheme.toml; do not edit.' % scheme, '# %s, %s variant.' % (v.title, s), '',
            '[ColorScheme]', 'active_colors=' + palette(r), 'disabled_colors=' + palette(r, True), 'inactive_colors=' + palette(r), '']) 
    return scheme, out

if __name__ == '__main__': A.main(build, 'qtct', __doc__)
