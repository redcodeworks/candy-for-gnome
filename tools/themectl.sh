# Featured themes: listed first (marked with a star) in list-themes and the install/switch/remove checklists, in this order, then every
# other scheme alphabetically. The ONE place to change the favorites; tools/test.sh and CI read the same line (FEATURED_THEMES may be
# set in the environment to override it).
FEATURED_THEMES="${FEATURED_THEMES-nordic gruvbox-material everforest tokyo-night dracula fairy-floss catppuccin aubergine}"

items=(); labels=(); declare -A i_src i_dir i_var
set_name() {       # set name of an icon dir $1: its index.theme Name= when that is a plain id, else $2
    local nm; nm=$(sed -n 's/^Name=//p' "$1/index.theme" 2>/dev/null | head -n1 | tr -d '\r')
    case "$nm" in ""|*[[:space:]/]*) echo "$2" ;; *) echo "$nm" ;; esac
}
add_item() { items+=("$1"); labels+=("$1  ($2)"); i_src[$1]="$2"; i_dir[$1]="$3"; i_var[$1]="$4"; }
load_items() {
    items=(); labels=(); i_src=(); i_dir=(); i_var=()
    if [ "$kind" = themes ]; then
        local all=() ordered=() f d dd star; local -A isfeat=()   # pure bash: this runs on every invocation, and there are hundreds of schemes
        for p in "$troot"/*/palette.toml; do
            d="${p%/palette.toml}"; sc="${d##*/}"; [ -d "$d/gtk" ] && all+=("$sc")
        done
        mapfile -t all < <(printf '%s\n' "${all[@]}" | LC_ALL=C sort)
        for f in $FEATURED_THEMES; do isfeat[$f]=1; done
        for f in $FEATURED_THEMES; do for sc in "${all[@]}"; do [ "$sc" = "$f" ] && ordered+=("$sc"); done; done
        for sc in "${all[@]}"; do [ -n "${isfeat[$sc]:-}" ] || ordered+=("$sc"); done
        for sc in "${ordered[@]}"; do
            gtk=""; shell=""
            for d in "$troot/$sc"/gtk/*/; do
                dd="${d%/}"; n="${dd##*/}"
                case "$n" in
                    *-Shell-*) v="${n##*-Shell-}"; shell="${shell:+$shell/}${v,,}" ;;
                    *) gtk="GTK 3/4" ;;
                esac
            done
            what="${gtk}${gtk:+${shell:+ + }}${shell:+GNOME Shell $shell}"
            star=""; [ -n "${isfeat[$sc]:-}" ] && star="★ "
            items+=("$sc"); labels+=("$star$sc  ($what)")
        done
    else
        local n t v base
        for n in "${src_names[@]}"; do   # from the registry only: no clone, no network
            case "${src_layout[$n]}" in
                top) for t in ${src_extra[$n]}; do add_item "${t#*=}" "$n" "${t%%=*}" ""; done ;;
                root) add_item "${src_extra[$n]}" "$n" "" "" ;;
                script|script-t) base="${n^}"
                        for v in ${src_extra[$n]}; do
                            if [ "$v" = standard ]; then add_item "$base" "$n" "" "$v"; else add_item "$base-$v" "$n" "" "$v"; fi
                        done ;;
                *) echo "icon-sources.conf: unknown layout '${src_layout[$n]}' for $n" >&2 ;;
            esac
        done
    fi
}
is_script() { case "${src_layout[${i_src[$1]}]}" in script|script-t) return 0 ;; *) return 1 ;; esac; }   # sets built by the upstream install.sh
folders_of() {   # installable folder names of item $1 (exactly these: never a glob, so removing Tela keeps Tela-blue)
    if [ "$kind" = themes ]; then for d in "$troot/$1"/gtk/*/; do d="${d%/}"; echo "${d##*/}"; done
    elif is_script "$1"; then echo "$1"; echo "$1-dark"; echo "$1-light"
    else echo "$1"; fi
}
build_dir=""
prepare_item() { # icons, script layout: run the upstream install.sh for the variant into a temp dir (never the real destination)
    [ "$kind" = icons ] || return 0
    is_script "$1" || return 0
    local d f v; d=$(clone_of "${i_src[$1]}"); build_dir=$(mktemp -d); v="${i_var[$1]}"
    echo "Building $1 with the upstream install.sh (variant $v) ..."
    if [ "${src_layout[${i_src[$1]}]}" = script-t ]; then   # WhiteSur style: -n NAME -t VARIANT, the blue one is "default"
        if [ "$v" = standard ]; then v=default; fi
        (cd "$d" && ./install.sh -d "$build_dir" -n "${i_src[$1]^}" -t "$v" >/dev/null 2>&1) || { echo "install.sh failed for $1" >&2; return 1; }
    else (cd "$d" && ./install.sh -d "$build_dir" "$v" >/dev/null 2>&1) || { echo "install.sh failed for $1" >&2; return 1; }
    fi
    while read -r f; do [ -d "$build_dir/$f" ] || { echo "install.sh did not produce $f" >&2; return 1; }; done < <(folders_of "$1")
}
shared_bases() {  # hidden base dirs (e.g. .Fluent-base) that the installed folders of item $1 link into
    local f
    while read -r f; do [ -d "$dest/$f" ] && find "$dest/$f" -type l -printf '%l\n' 2>/dev/null; done < <(folders_of "$1") \
        | sed -n 's|^\(\.\./\)\{1,\}\(\.[^./][^/]*\)/.*|\2|p' | sort -u || true
}
finish_item() { if [ -n "$build_dir" ]; then rm -rf "${build_dir:?}"; build_dir=""; fi; }
# ---- collision guard -----------------------------------------------------------------------------
# A folder in $dest is ours when it has the marker file, or (installs from before the marker) when its index.theme is
# byte-identical to the index.theme of our source for that folder (themes: the generated one of the scheme; icons: the
# cloned or freshly built one; script-built sets have no source copy outside install, so they are adopted on install only).
marker=.candy-for-gnome
src_index() {    # src_index ITEM FOLDER: our source's index.theme for that folder (may not exist)
    if [ "$kind" = themes ]; then echo "$troot/$1/gtk/$2/index.theme"; return; fi
    case "${src_layout[${i_src[$1]}]}" in
        top)    echo "$(clone_of "${i_src[$1]}")/${i_dir[$1]}/index.theme" ;;
        root)   echo "$(clone_of "${i_src[$1]}")/index.theme" ;;
        script|script-t) [ -n "$build_dir" ] && echo "$build_dir/$2/index.theme" || echo "" ;;
    esac
}
is_ours() {      # is_ours DIR SRC_INDEX
    [ -d "$1" ] || return 1
    marker_present "$1" && return 0
    [ -f "$1/$old_marker" ] && return 0     # carries the old gnome-themes marker: replaced like our own (install and update adopt it with the new marker)
    [ -n "${2:-}" ] && [ -f "$2" ] && [ -f "$1/index.theme" ] && cmp -s "$2" "$1/index.theme"
}
# may_touch DIR SRC_INDEX VERB: 0 when DIR is absent, ours, FORCE=1 or the user says yes in a terminal; else 1 (with a message)
may_touch() {
    local d="$1" a
    [ -e "$d" ] || [ -L "$d" ] || return 0
    if is_ours "$d" "${2:-}" && ! { [ "${3:-}" = Remove ] && [ -f "$d/$old_marker" ] && ! marker_present "$d"; }; then return 0; fi   # a removal leaves old-marker folders alone
    [ "${FORCE:-}" = 1 ] && return 0
    if [ "$tty_in" = 1 ]; then
        read -r -u 3 -p "$d exists and was not installed by candy-for-gnome. ${3:-Replace} it? [y/N] " a || a=n
        case "$a" in [yY]*) return 0 ;; esac
        echo "Left $d alone." >&2; return 1
    fi
    echo "Refused: $d exists and was not installed by candy-for-gnome; left alone (FORCE=1 replaces it, or run in a terminal to be asked)." >&2
    return 1
}
# The marker file is `key=value` lines (schema=1, kind, name, folder, variant, style, source, source_commit, installed_at, updated_at, installer). A
# one-line bare marker from earlier versions (just the name) still counts as ours and reads as the name; the next install or update of that folder
# rewrites it in the new format. ONE reader for all of it: marker_present (is it ours) and marker_read DIR KEY.
marker_present() { [ -f "$1/$marker" ]; }
marker_read() {   # marker_read DIR KEY: the value (empty when absent); a legacy bare marker answers `name` with its line and nothing else
    local f="$1/$marker"
    [ -f "$f" ] || return 0
    if ! grep -q '=' "$f"; then [ "$2" = name ] && head -n1 "$f" | tr -d '\r'; return 0; fi
    sed -n "s/^$2=//p" "$f" | head -n1 | tr -d '\r'
}
now_utc() { date -u +%Y-%m-%dT%H:%M:%SZ; }
mark_old=""   # installed_at of the marker that was replaced (the caller reads it before it removes the old folder)
mark_dir() {   # mark_dir DIR ITEM FOLDER: write the marker (name = what the bare marker held)
    local d="$1" it="$2" f="$3" n kd src url sc="" var="" sty="" inst now
    now=$(now_utc); inst="${mark_old:-$now}"
    if [ "$kind" = themes ]; then
        kd=theme; url=$(git -C "$root" remote get-url origin 2>/dev/null || echo https://github.com/redcodeworks/candy-for-gnome); sc=$(git -C "$root" rev-parse HEAD 2>/dev/null || true)
    else
        kd=icon; src="${i_src[$it]:-}"; url="${src_url[$src]:-}"
        [ -n "$src" ] && sc=$(git -C "$(clone_of "$src")" rev-parse HEAD 2>/dev/null || true)
        if is_script "$it" 2>/dev/null; then var="${i_var[$it]:-}"; sty=$(style_label "$it" "$f"); fi
    fi
    {
        printf 'schema=1\nkind=%s\nname=%s\nfolder=%s\nvariant=%s\nstyle=%s\n' "$kd" "$it" "$f" "$var" "$sty"
        printf 'source=%s\nsource_commit=%s\ninstalled_at=%s\nupdated_at=%s\ninstaller=%s\n' "$url" "$sc" "$inst" "$now" "$(git -C "$root" rev-parse --short=12 HEAD 2>/dev/null || true)"
    } > "$d/$marker"
}
adw_label="Adwaita (GNOME default)"; items_adw=0
add_adwaita() {   # switch and list only: the GNOME default as the first entry (nothing is installed or removed for it; it is the system's own)
