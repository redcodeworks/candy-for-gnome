    done
}

# ---- prompts -------------------------------------------------------------------------------------
# Terminal UI (no dependencies): up/down or j/k move, SPACE toggles, a all, n none, ENTER confirms, q cancels. Without a
# terminal the numbered lists below are used.
# Terminal checklist for bash: arrow keys or j/k move, SPACE toggles, a = all, n = none, Enter confirms, q cancels.
# No dependencies. Draws on stderr, reads the keyboard from /dev/tty. Needs: labels[] (display text per index),
# on[] (1 = ticked) for tui_many. Returns 2 when there is no terminal, so the caller can fall back to a numbered list.
#   tui_many HEADER IDX...   sets chosen=(ticked indexes among IDX); returns 1 when cancelled
#   tui_one  HEADER IDX...   sets pick=<index> (empty when cancelled); tui_cur=N (position within IDX) puts the cursor there
_tui_read_key() {   # sets key to: up down pgup pgdn first last space enter quit all none filter resize or the raw character (tui_raw=1: raw characters, esc, enter, backspace only)
    local k rest="" rc=0
    IFS= read -rsn1 -t 0.3 k </dev/tty || rc=$?
    if [ "$rc" -gt 128 ]; then key=tick; return; fi      # no key within 0.3 s: _tui_wait_key checks whether the terminal was resized
    if [ "$rc" -ne 0 ]; then key=quit; return; fi
    if [ "${tui_raw:-0}" = 1 ]; then
        case "$k" in
            $'\e') IFS= read -rsn2 -t 0.05 rest </dev/tty || rest=""; key=esc ;;
            '') key=enter ;; $'\x7f'|$'\b') key=backspace ;; *) key="$k" ;;
        esac
        return
    fi
    case "$k" in
        $'\e') IFS= read -rsn2 -t 0.05 rest </dev/tty || rest=""
               case "$rest" in [\[O][1-6]) IFS= read -rsn1 -t 0.05 k </dev/tty || k=""; rest="$rest$k" ;; esac   # [5~ [6~ [1~ [4~ : the third character
               case "$rest" in
                   '[A'|'OA') key=up ;; '[B'|'OB') key=down ;; '[H'|'OH'|'[1~') key=first ;; '[F'|'OF'|'[4~') key=last ;;
                   '[5~') key=pgup ;; '[6~') key=pgdn ;; *) key=quit ;;
               esac ;;
        ' ') key=space ;; '') key=enter ;; k) key=up ;; j) key=down ;; a) key=all ;; n) key=none ;; q) key=quit ;; /) key=filter ;; g) key=first ;; G) key=last ;;
        *) key="$k" ;;
    esac
}
_tui_wait_key() {   # _tui_wait_key: like _tui_read_key, but returns key=resize when the terminal size changed while waiting (SIGWINCH cannot interrupt `read` portably)
    local sz0 sz; sz0=$(stty size </dev/tty 2>/dev/null)
    while true; do
        _tui_read_key; [ "$key" = tick ] || return
        sz=$(stty size </dev/tty 2>/dev/null); if [ "$sz" != "$sz0" ]; then key=resize; return; fi
    done
}
_tui_end() { stty "$_tui_saved" </dev/tty 2>/dev/null; printf '\e[?25h\n' >&2; trap - INT; }
# _tui_run MODE HEADER IDX... ; MODE many|one. A window of the list is drawn: one header line, H list lines, one footer line, where H = terminal
# rows - 2 (at least 1, at most the number of entries). `top` is the first shown row of the (filtered) list and moves by the minimum needed to keep
# the cursor row visible; the size is read again on every redraw and on SIGWINCH. The frame has a fixed height and is redrawn in place (cursor up,
# clear to end of line), so the terminal never scrolls once the frame is drawn. Lines are cut to the terminal width. Keys: up/down j/k, PgUp/PgDn,
# Home/End or g/G, SPACE toggles, a/n act on the shown entries, "/" filters (type to narrow by substring, case-insensitive; Enter keeps the filter,
# Esc clears it; ticks are per entry and survive filtering), ENTER confirms, q cancels. The footer shows "first-last of total", the filter and the
# tick count. Ctrl-C and every exit restore the terminal (stty, cursor).
_tui_run() {
    local mode="$1" header="$2"; shift 2; local cand=("$@") n=$# cur="${tui_cur:-0}" top=0 i r line first=1 filt="" fmode=0 vis=() nv lf
    local rows=24 cols=80 H=1 prevH=0 prevC=0 sz mark ticked foot hint swp swn pre
    [ -t 0 ] && [ -t 2 ] && [ -r /dev/tty ] || return 2
    _tui_saved=$(stty -g </dev/tty) || return 2
    trap '_tui_end; exit 130' INT
    stty -echo -icanon min 1 time 0 </dev/tty; printf '\e[?25l' >&2
    hint="SPACE toggles, / filters, a all, n none, ENTER confirms, q cancels"
    [ "$mode" = one ] && hint="/ filters, ENTER selects, q cancels"
    while true; do
        vis=(); lf="${filt,,}"
        for i in "${!cand[@]}"; do
            if [ -z "$lf" ]; then vis+=("$i"); else line="${labels[${cand[i]}],,}"; case "$line" in *"$lf"*) vis+=("$i") ;; esac; fi
        done
        nv=${#vis[@]}
        sz=$(stty size </dev/tty 2>/dev/null) && { rows=${sz% *}; cols=${sz#* }; }
        [ "${rows:-0}" -ge 1 ] 2>/dev/null || rows=24; [ "${cols:-0}" -ge 10 ] 2>/dev/null || cols=80
        H=$((rows - 2)); [ "$H" -lt 1 ] && H=1; [ "$H" -gt "$n" ] && H=$n; [ "$H" -lt 1 ] && H=1
        if [ "$nv" -gt 0 ]; then
            [ "$cur" -ge "$nv" ] && cur=$((nv-1)); [ "$cur" -lt 0 ] && cur=0
            [ "$cur" -lt "$top" ] && top=$cur
            [ "$cur" -ge $((top + H)) ] && top=$((cur - H + 1))
        else cur=0; top=0; fi
        [ "$top" -gt $((nv - H)) ] && top=$((nv - H)); [ "$top" -lt 0 ] && top=0
        if [ "$first" -eq 1 ]; then :
        elif [ "$prevH" -ne "$H" ] || [ "$prevC" -ne "$cols" ]; then printf '\e[2J\e[H' >&2    # the terminal was resized: clear it and draw the frame from the top
        else printf '\e[%dA' "$((H+1))" >&2; fi     # the cursor rests on the footer row, the last row of the frame
        first=0; prevH=$H; prevC=$cols
        ticked=0; if [ "$mode" = many ]; then for i in "${cand[@]}"; do [ "${on[i]:-0}" -eq 1 ] && ticked=$((ticked+1)); done; fi
        if [ "$fmode" -eq 1 ]; then line="$header  filter: ${filt}_ (Enter keeps it, Esc clears it)"
        elif [ -n "$filt" ]; then line="$header  [filter: $filt]"
        else line="$header"; fi
        printf '\r\e[K%s\n' "${line:0:$((cols-1))}" >&2
        for ((r=0; r<H; r++)); do
            if [ $((top + r)) -ge "$nv" ]; then printf '\r\e[K\n' >&2; continue; fi
            i=${vis[top+r]}; line="${labels[${cand[i]}]}"; swp="${swatch[${cand[i]}]:-}"; swn="${swatch_w[${cand[i]}]:-0}"
            pre=""; if [ "$mode" = many ]; then mark=" "; [ "${on[${cand[i]}]:-0}" -eq 1 ] && mark="x"; pre="[$mark] "; fi
            line="${pre}${swp}${line:0:$((cols-3-${#pre}-swn))}"   # the swatch (escapes) is not counted: swn is its visible width
            if [ $((top + r)) -eq "$cur" ]; then printf '\r\e[K\e[7m> %s\e[0m\n' "$line" >&2; else printf '\r\e[K  %s\n' "$line" >&2; fi
        done
        if [ "$nv" -eq 0 ]; then foot="0 of 0 shown (of $n)"; else foot="$((top+1))-$((top+H<nv ? top+H : nv)) of $nv"; fi
        [ -n "$filt" ] && foot="$foot  filter: $filt"
        [ "$mode" = many ] && foot="$foot  $ticked ticked"
        foot="$foot  $hint"
        printf '\r\e[K%s\r' "${foot:0:$((cols-1))}" >&2     # no newline: the cursor stays on the footer row, so a full-height frame never scrolls the terminal
        if [ "$fmode" -eq 1 ]; then
            tui_raw=1 _tui_wait_key
            case "$key" in
                resize) continue ;;
                enter) fmode=0 ;;
                esc) filt=""; fmode=0 ;;
                backspace) filt="${filt%?}"; cur=0; top=0 ;;
                [[:print:]]) filt+="$key"; cur=0; top=0 ;;
            esac
            continue
        fi
        _tui_wait_key
        case "$key" in
            resize) ;;
            filter) fmode=1 ;;
            up) [ "$nv" -gt 0 ] && cur=$(( (cur + nv - 1) % nv )) ;;
            down) [ "$nv" -gt 0 ] && cur=$(( (cur + 1) % nv )) ;;
            pgup) [ "$nv" -gt 0 ] && { cur=$((cur - H)); [ "$cur" -lt 0 ] && cur=0; } ;;
            pgdn) [ "$nv" -gt 0 ] && { cur=$((cur + H)); [ "$cur" -ge "$nv" ] && cur=$((nv-1)); } ;;
            first) cur=0 ;;
            last) [ "$nv" -gt 0 ] && cur=$((nv-1)) ;;
            space) [ "$mode" = many ] && [ "$nv" -gt 0 ] && on[${cand[${vis[cur]}]}]=$((1 - ${on[${cand[${vis[cur]}]}]:-0})) ;;
            all) [ "$mode" = many ] && for i in "${vis[@]}"; do on[${cand[i]}]=1; done ;;
            none) [ "$mode" = many ] && for i in "${vis[@]}"; do on[${cand[i]}]=0; done ;;
            enter) if [ "$mode" = one ]; then [ "$nv" -gt 0 ] || continue; pick="${cand[${vis[cur]}]}"; else chosen=(); for i in "${cand[@]}"; do [ "${on[i]:-0}" -eq 1 ] && chosen+=("$i"); done; fi; _tui_end; return 0 ;;
            quit) if [ "$mode" = one ]; then pick=""; else chosen=(); fi; _tui_end; return 1 ;;
        esac
    done
}
tui_many() { chosen=(); _tui_run many "$@"; }
tui_one()  { pick=""; _tui_run one "$@"; }

# ---- gum picker -------------------------------------------------------------------------------------
# The checklists use `gum choose` (Bluefin style: ◉ / ○ / ▸ prefixes, section headings as plain items that are never returned) when gum is on PATH
# and there is a terminal; otherwise the built-in picker above (with its `/` filter and viewport), and without a terminal the numbered list.
# THEMES_PICKER=gum|builtin forces one (gum missing: a warning and the built-in; a forced gum does not need a terminal, which the tests use).
picker_used=builtin
# after_install_switch NAME... : on a terminal, offer the single-choice switch menu of the installed ${noun}s (just-installed first, highlighted) and, when
# one is chosen, run exactly the switch path (a new process: `themectl.sh <kind> switch <name>`). THEMES_SWITCH_AFTER_INSTALL=0 turns it off (both kinds).
after_install_switch() {
    [ "${THEMES_SWITCH_AFTER_INSTALL:-1}" != 0 ] || return 0
    [ "$tty_in" -eq 1 ] && [ -t 2 ] || return 0
    local first=() rest=() i nm cmd="switch-theme"; [ "$kind" = icons ] && cmd="switch-icon"
    for nm in "$@"; do i=$(index_of "$nm") && first+=("$i"); done
    [ "${#first[@]}" -gt 0 ] || return 0
    for i in "${!items[@]}"; do
        is_installed "${items[i]}" || continue
        case " ${first[*]} " in *" $i "*) ;; *) rest+=("$i") ;; esac
    done
    tui_cur=0; pick_keep_order=1; choose_one "Switch to which $noun now?" "${first[@]}" "${rest[@]}"; pick_keep_order=0
    if [ -z "${pick:-}" ]; then echo "Not switching. To switch later: just $cmd ${items[${first[0]}]}"; return 0; fi
    exec "${BASH_SOURCE[0]}" "$kind" switch "${items[pick]}"
}
nothing_selected() {   # the one-line hint when a checklist ends with nothing ticked (it depends on the picker that was shown)
    case "$picker_used" in gum) echo "Nothing selected: nothing was ticked. Press x on an entry, then Enter." ;; *) echo "Nothing selected: nothing was ticked. Press SPACE on an entry, then Enter." ;; esac
}
pick_handler() {
    case "${THEMES_PICKER:-}" in
        builtin) echo builtin; return ;;
        gum) if command -v gum >/dev/null 2>&1; then echo gum; else echo "THEMES_PICKER=gum requested but gum is not on PATH; using the built-in picker." >&2; echo builtin; fi; return ;;
    esac
    if [ -t 0 ] && [ -t 2 ] && [ -r /dev/tty ] && command -v gum >/dev/null 2>&1; then echo gum; else echo builtin; fi
}
# gum_run MODE HEADER IDX... : sets chosen=(indexes) (many) or pick=index (one); an empty result (Esc, nothing ticked) leaves them empty
gum_run() {
    local mode="$1" header="$2"; shift 2; local cand=("$@") i lab l out line hn rows=24 sz h sel="" items=()
    local -A idx_of=()
    # featured entries (starred) first, then the rest; NO heading or divider rows: gum cannot make a row unselectable, and every row must be a real choice
    item_of() { echo "${swatch[$1]:-}${labels[$1]}"; }   # a swatch is part of the item text; gum returns the item WITHOUT its escapes (checked), so the key is the plain text
    if [ "${pick_keep_order:-0}" = 1 ]; then for i in "${cand[@]}"; do items+=("$(item_of "$i")"); done   # the caller ordered the list (just-installed first)
    else
        for i in "${cand[@]}"; do [ "${items_adw:-}" = 1 ] && [ "${labels[i]}" = "$adw_label" ] && items+=("$(item_of "$i")"); done   # the Adwaita entry stays first
        for i in "${cand[@]}"; do [[ "${labels[i]}" == "★ "* ]] && items+=("$(item_of "$i")"); done
        for i in "${cand[@]}"; do [[ "${labels[i]}" == "★ "* ]] || { [ "${items_adw:-}" = 1 ] && [ "${labels[i]}" = "$adw_label" ]; } || items+=("$(item_of "$i")"); done
    fi
    for i in "${cand[@]}"; do idx_of[$(printf '%*s' "${swatch_w[i]:-0}" '')${labels[i]}]=$i; [ "$mode" = many ] && [ "${on[i]:-0}" -eq 1 ] && sel+="${sel:+,}${labels[i]}"; done
    sz=$(stty size </dev/tty 2>/dev/null) && rows=${sz% *}
    h=$((rows - 4)); [ "$h" -gt "${#items[@]}" ] && h=${#items[@]}; [ "$h" -lt 5 ] && h=5
    # colors: terminal palette colors only (ANSI 0-15 or the default foreground), never gum's fixed 256-color pink/purple; a variable the user set is left alone
    local colors=()
    [ -n "${GUM_CHOOSE_CURSOR_FOREGROUND+x}" ] || colors+=(--cursor.foreground=2)
    [ -n "${GUM_CHOOSE_SELECTED_FOREGROUND+x}" ] || colors+=(--selected.foreground=2)
    [ -n "${GUM_CHOOSE_HEADER_FOREGROUND+x}" ] || colors+=(--header.foreground=)
    [ -n "${GUM_CHOOSE_ITEM_FOREGROUND+x}" ] || colors+=(--item.foreground=)
    local args=(choose "${colors[@]}" --height "$h" --cursor "▸  " --cursor-prefix "○  " --selected-prefix "◉  " --unselected-prefix "○  ")
    if [ "$mode" = many ]; then args+=(--no-limit --header "$header (x marks an entry, ENTER confirms the marked ones; ENTER with none marked does nothing; Esc cancels)"); [ -n "$sel" ] && args+=(--selected "$sel")
    else args+=(--limit 1 --header "$header (ENTER selects, Esc cancels)"); fi
    out=$(gum "${args[@]}" "${items[@]}" || true)
    chosen=(); pick=""
    while IFS= read -r line; do
        [ -n "$line" ] || continue
        if [ -n "${idx_of[$line]+x}" ]; then i=${idx_of[$line]}; else   # a label that came back changed: match by name (star and description stripped)
            line="${line#"${line%%[![:space:]]*}"}"; lab="${line#★ }"; lab="${lab%%  (*}"; i=""
            for hn in "${cand[@]}"; do l="${labels[hn]#★ }"; l="${l%%  (*}"; if [ "$l" = "$lab" ]; then i=$hn; break; fi; done
            [ -n "$i" ] || continue
        fi
        if [ "$mode" = many ]; then chosen+=("$i"); else pick="$i"; break; fi
    done <<< "$out"
}

# choose_many HEADER IDX... : tick entries from the candidate indexes; sets chosen=(indexes). Preselected = on[]
chosen=(); on=()
choose_many() {
    local header="$1"; shift; local cand=("$@") i a mark rc=0 handler
    chosen=()
    [ "$kind" != themes ] || theme_swatches
    handler=$(pick_handler); picker_used=$handler
    if [ "$handler" = gum ]; then
        gum_run many "$header" "${cand[@]}"; return 0
    fi
    tui_many "$header" "${cand[@]}" || rc=$?
    if [ "$rc" -eq 1 ]; then echo "Cancelled."; exit 0
    elif [ "$rc" -eq 2 ]; then
        while true; do
            echo; echo "$header:"
            for i in "${!cand[@]}"; do
                mark=" "; if [ "${on[${cand[i]}]:-0}" -eq 1 ]; then mark="x"; fi
                printf ' %2d) [%s] %s\n' "$((i+1))" "$mark" "${labels[${cand[i]}]}"
            done
            read -r -p "Number toggles, a = all, n = none, Enter = confirm, q = quit: " a || a=q
            case "$a" in
                "") break ;;
                q) echo "Cancelled."; exit 0 ;;
                a) for i in "${cand[@]}"; do on[i]=1; done ;;
                n) for i in "${cand[@]}"; do on[i]=0; done ;;
                *[!0-9]*) echo "Not a number: $a" ;;
                *) if [ "$a" -ge 1 ] && [ "$a" -le "${#cand[@]}" ]; then i=${cand[$((a-1))]}; on[i]=$((1-${on[i]:-0})); else echo "Out of range: $a"; fi ;;
            esac
        done
        for i in "${cand[@]}"; do if [ "${on[i]:-0}" -eq 1 ]; then chosen+=("$i"); fi; done
    fi
}
# choose_one HEADER IDX... : pick exactly one; sets pick=index (empty when cancelled)
pick=""
choose_one() {
    local header="$1"; shift; local cand=("$@") i a rc=0 handler
    pick=""
    [ "$kind" != themes ] || theme_swatches
    handler=$(pick_handler)
    if [ "$handler" = gum ]; then gum_run one "$header" "${cand[@]}"; return 0; fi
    tui_one "$header" "$@" || rc=$?
    if [ "$rc" -eq 2 ]; then
        echo; echo "$header:"
        for i in "${!cand[@]}"; do printf ' %2d) %s\n' "$((i+1))" "${labels[${cand[i]}]}"; done
        read -r -p "Number (Enter cancels): " a || a=""
        if [[ "$a" =~ ^[0-9]+$ ]] && [ "$a" -ge 1 ] && [ "$a" -le "${#cand[@]}" ]; then pick="${cand[$((a-1))]}"; fi
    fi
}

# ---- Ptyxis palettes (themes only) ----------------------------------------------------------------------------
pty_ours() {   # pty_ours SCHEME FILE (palette, style scheme or app theme: the # // or XML marker; a directory = its flavor.toml)
    local f="$2"; [ -d "$f" ] && f="$f/flavor.toml"
    [ -f "$f" ] && { grep -qxF "# candy-for-gnome: $1" "$f" || grep -qxF "<!-- candy-for-gnome: $1 -->" "$f" || grep -qxF "// candy-for-gnome: $1" "$f"; }
}
# pty_may_touch SCHEME VERB FILE: 0 when the palette file is absent, ours, FORCE=1 or the user says yes in a terminal (same rules as folders)
pty_may_touch() {
    local d a; d="$3"
    [ -e "$d" ] || return 0
    pty_ours "$1" "$d" && return 0
    [ "${FORCE:-}" = 1 ] && return 0
    if [ "$tty_in" = 1 ]; then
        read -r -u 3 -p "$d exists and was not installed by candy-for-gnome. ${2:-Replace} it? [y/N] " a || a=n
        case "$a" in [yY]*) return 0 ;; esac
        echo "Left $d alone." >&2; return 1
    fi
    echo "Refused: $d exists and was not installed by candy-for-gnome; left alone (FORCE=1 replaces it, or run in a terminal to be asked)." >&2
    return 1
}
pty_cleanup() {  # delete leftover generated palette files of earlier versions: only files that carry our marker line
    local f; [ -d "$pty_dir" ] || return 0
    for f in "$pty_dir"/*.palette; do
        [ -f "$f" ] && grep -qE '^# candy-for-gnome: [A-Za-z0-9._-]+[[:space:]]*$' "$f" || continue
        rm -f "$f" && echo "Removed old generated Ptyxis palette $f (Ptyxis built-in palettes are used now)."
    done
}
dq() { grep -o "'[^']*'" | tr -d "'"; }   # the quoted strings of a GVariant text value
pty_toml() {  # pty_toml SCHEME KEY: the top-level string value of KEY in scheme.toml (empty when absent)
    awk -v k="$2" '/^\[/ { exit } index($0, k " = \"") == 1 { v = substr($0, length(k) + 5); sub(/".*$/, "", v); print v; exit }' "$troot/$1/scheme.toml" 2>/dev/null | tr -d '\r'
}
pty_mode() {  # dark or light, from the system colour scheme (prefer-dark = dark, prefer-light = light; `default` = dark only when the GTK theme in use is a dark one, else light; no gsettings = dark)
    local cs gt; cs=$(gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null | tr -d "'") || cs=""
    case "$cs" in
        prefer-dark) echo dark ;;
        prefer-light) echo light ;;
        default) gt=$(gsettings get org.gnome.desktop.interface gtk-theme 2>/dev/null | tr -d "'") || gt=""
                 case "$gt" in *[Dd]ark*) echo dark ;; *) echo light ;; esac ;;
        *) echo dark ;;
    esac
}
pty_switch() {   # set the palette id on the default profile and on every profile that already has a palette key
    local s="$1" id lt mode uuids u def sel=() done_n=0 got known
    id=$(pty_toml "$s" ptyxis); lt=$(pty_toml "$s" ptyxis_light)
    [ -n "$id" ] || { echo "Ptyxis palette not applied: $s declares no \`ptyxis\` id in its scheme.toml."; return 0; }
    if [ -n "$lt" ] && [ "$lt" != "$id" ]; then
        mode=$(pty_mode)
        if [ "$mode" = light ]; then id="$lt"; fi
        echo "Ptyxis: $s has a separate palette per mode; the system colour scheme reads as $mode, so the palette id is '$id'. Run switch-theme again after changing between light and dark to pick the other one."
    fi
    command -v dconf >/dev/null 2>&1 || { echo "Ptyxis palette not applied: dconf not found. Pick the built-in with id '$id' in Ptyxis > Preferences > Palette."; return 0; }
    uuids=$(dconf read /org/gnome/Ptyxis/profile-uuids 2>/dev/null | dq || true)
    def=$(dconf read /org/gnome/Ptyxis/default-profile-uuid 2>/dev/null | dq | head -n1 || true)
    [ -n "$def" ] || def=$(printf '%s\n' "$uuids" | head -n1)
    if [ -z "$def" ]; then
        echo "Ptyxis palette not applied: no Ptyxis profile found (settings absent; start Ptyxis once, then run switch-theme again, or pick the built-in with id '$id' in Preferences > Palette)."
        return 0
    fi
    sel=("$def")
    for u in $uuids; do
        [ "$u" = "$def" ] && continue
        [ -n "$(dconf read "/org/gnome/Ptyxis/Profiles/$u/palette" 2>/dev/null || true)" ] && sel+=("$u")
    done
    for u in "${sel[@]}"; do
        dconf write "/org/gnome/Ptyxis/Profiles/$u/palette" "'$id'" && done_n=$((done_n+1))
        got=$(dconf read "/org/gnome/Ptyxis/Profiles/$u/palette" 2>/dev/null || true)
        echo "Ptyxis palette key reads $got (profile $u)"
    done
    echo "Ptyxis palette id is now '$id' (Ptyxis built-in) on $done_n profile(s) (the default one, plus those that already had a palette set)."
    if known=$(python3 -I "$root/tools/ptyxis-ids.py" ids 2>/dev/null); then
        printf '%s\n' "$known" | grep -qxF -- "$id" || echo "WARNING: '$id' is not a built-in palette id of the installed Ptyxis; Ptyxis would fall back to its default palette (ids are case-sensitive; see tools/ptyxis-ids.py list)."
    else echo "Note: the Ptyxis binary could not be read, so the id was not checked against its built-in palettes."; fi
}

# ---- GtkSourceView style schemes (themes only) -------------------------------------------------------------------
gsv_apps=(org.gnome.TextEditor org.gnome.Builder)
gsv_app_present() { [ -d "$fp_apps/$1" ] || { command -v flatpak >/dev/null 2>&1 && flatpak info "$1" >/dev/null 2>&1; }; }
gsv_dirs() {   # the styles directories to fill: the user's own, and the data directory of each installed Flatpak editor
    echo "$gsv_dir"; local a; for a in "${gsv_apps[@]}"; do if gsv_app_present "$a"; then echo "$fp_apps/$a/data/gtksourceview-5/styles"; fi; done
}
gsv_files() { local f; for f in "$troot/$1"/gtksourceview/*.xml; do [ -f "$f" ] && basename "$f"; done; }   # file names of scheme $1
gsv_install() {  # gsv_install SCHEME: copy the style schemes into every styles directory
    local s="$1" d f n=0
    while read -r d; do
        while read -r f; do
            pty_may_touch "$s" Replace "$d/$f" || continue
            mkdir -p "$d"; cp "$troot/$s/gtksourceview/$f" "$d/$f"; n=$((n+1))
        done < <(gsv_files "$s")
    done < <(gsv_dirs)
    if [ "$n" -gt 0 ]; then echo "Installed GtkSource style scheme(s) of $s ($n file(s); editors: $gsv_dir and installed Flatpak editors)."; fi
}
gsv_refresh() {  # update: refresh only the files that exist and are ours
    local s="$1" d f
    while read -r d; do
        while read -r f; do
            [ -f "$d/$f" ] && pty_ours "$s" "$d/$f" && cp "$troot/$s/gtksourceview/$f" "$d/$f"
        done < <(gsv_files "$s")
    done < <(gsv_dirs)
    return 0
}
gsv_remove() {
    local s="$1" d f
    while read -r d; do
        while read -r f; do
            [ -e "$d/$f" ] || continue
            pty_may_touch "$s" Remove "$d/$f" || continue
            rm -f "$d/$f"; echo "Removed $d/$f"
        done < <(gsv_files "$s")
    done < <(gsv_dirs)
    return 0
}
gsv_flatpak() { command -v flatpak >/dev/null 2>&1 && flatpak info "$1" >/dev/null 2>&1; }   # is this app an installed Flatpak?
gsv_set_flatpak() {   # gsv_set_flatpak APP SCHEMA KEY ID LABEL: set the key in the app's own sandbox store, report only what a read-back there shows
    local app="$1" schema="$2" key="$3" id="$4" label="$5" got
    flatpak run --command=gsettings "$app" set "$schema" "$key" "$id" </dev/null >/dev/null 2>&1 || true
    got=$(flatpak run --command=gsettings "$app" get "$schema" "$key" </dev/null 2>/dev/null | tr -d "'") || got=""
    if [ "$got" = "$id" ]; then echo "$label (Flatpak) style scheme is now $id."
    else echo "WARNING: $label (Flatpak) style scheme reads '${got:-nothing}' after setting '$id'. Pick \"$id\" in its preferences."; fi
}
gsv_switch() {   # point Text Editor (and Builder when present) at the scheme's style scheme for the current light/dark mode
    local s="$1" id="" dark=1 f base
    [ -n "$(gsv_files "$s")" ] || return 0
    base="dark"; [ -f "$troot/$s/gtksourceview/candy-for-gnome-$s-dark.xml" ] || base="light"     # light-only scheme: only the -light id exists
    [ -f "$gsv_dir/candy-for-gnome-$s-$base.xml" ] && pty_ours "$s" "$gsv_dir/candy-for-gnome-$s-$base.xml" || { echo "GtkSource style scheme not applied: the installed copy is missing or not ours."; return 0; }
    gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null | grep -qi dark || dark=0
    id="candy-for-gnome-$s-$base"
    if [ "$dark" = 0 ] && [ -f "$troot/$s/gtksourceview/candy-for-gnome-$s-light.xml" ]; then id="candy-for-gnome-$s-light"; fi
    # Flatpak editors keep their OWN settings store (no dconf socket in the sandbox): the key is set and read back inside the sandbox.
    # The host dconf is written for an editor that is not a Flatpak, or when the host also has its schema.
    if gsv_flatpak org.gnome.TextEditor; then gsv_set_flatpak org.gnome.TextEditor org.gnome.TextEditor style-scheme "$id" "Text Editor"; fi
    if ! gsv_flatpak org.gnome.TextEditor || gsettings list-schemas 2>/dev/null | grep -qx org.gnome.TextEditor; then
        if command -v dconf >/dev/null 2>&1; then
            dconf write /org/gnome/TextEditor/style-scheme "'$id'" && echo "Text Editor style scheme is now $id (Text Editor also recolours its window from it)."
        else echo "GtkSource style scheme installed but not applied to Text Editor: dconf not found. Pick \"$id\" in the editor's preferences."; fi
    fi
    local b_host=0 b_fp=0
    gsettings list-schemas 2>/dev/null | grep -qx org.gnome.builder.editor && b_host=1
    gsv_flatpak org.gnome.Builder && b_fp=1
    if [ $b_fp = 1 ]; then gsv_set_flatpak org.gnome.Builder org.gnome.builder.editor style-scheme-name "$id" "Builder"; fi
    if [ $b_host = 1 ]; then
        if command -v dconf >/dev/null 2>&1; then dconf write /org/gnome/builder/editor/style-scheme-name "'$id'" && echo "Builder style scheme is now $id."
        else echo "Builder style scheme not applied: dconf not found. Pick \"$id\" in Builder's preferences."; fi
    fi
    if [ $b_host = 0 ] && [ $b_fp = 0 ]; then echo "Builder not found (no org.gnome.builder.editor schema, no Flatpak); its style scheme key was not set."; fi
    return 0
}

# ---- Ghostty themes (themes only; works on the config directory only, never assumes how Ghostty is installed) ----------------------
# Generated files per scheme (<scheme>/ghostty/): theme files candy-for-gnome-<scheme>-{dark,light} go to $cfg/ghostty/themes, the pair file
# <scheme>.conf (one `theme = dark:...,light:...` line) to $gh_data. switch-theme links $cfg/ghostty/candy-for-gnome.conf to the pair file and, after
# one question (default no), adds `config-file = ?candy-for-gnome.conf` to the user's main config. Nothing happens when $cfg/ghostty does not exist.
gh_dir="$cfg/ghostty"; gh_data="${XDG_DATA_HOME:-$HOME/.local/share}/candy-for-gnome/ghostty"
gh_link="$gh_dir/candy-for-gnome.conf"; gh_line='config-file = ?candy-for-gnome.conf'
gh_present() { [ -d "$gh_dir" ]; }
gh_themes() { local f; for f in "$(sdir "$1")"/ghostty/*; do [ -f "$f" ] && case "$f" in *.conf) ;; *) basename "$f" ;; esac; done; return 0; }   # theme file names of scheme $1
gh_targets() {   # gh_targets SCHEME: "<source file>|<destination>" for every file to install (theme files, then the pair file)
    local f; for f in $(gh_themes "$1"); do echo "$(sdir "$1")/ghostty/$f|$gh_dir/themes/$f"; done
    [ -f "$(sdir "$1")/ghostty/$1.conf" ] && echo "$(sdir "$1")/ghostty/$1.conf|$gh_data/$1.conf"; return 0
}
gh_install() {   # gh_install SCHEME: copy the theme files and the pair file (same collision guard as the other files)
    local s="$1" src dst n=0
    gh_present || return 0
    while IFS='|' read -r src dst; do
        pty_may_touch "$s" Replace "$dst" || continue
        mkdir -p "$(dirname "$dst")"; cp "$src" "$dst"; n=$((n+1))
    done < <(gh_targets "$s")
    if [ "$n" -gt 0 ]; then echo "Installed Ghostty theme file(s) of $s ($n file(s); $gh_dir/themes and $gh_data)."; fi
    return 0
}
gh_refresh() {   # update: refresh only the files that exist and are ours
    local s="$1" src dst
    gh_present || return 0
    while IFS='|' read -r src dst; do [ -f "$dst" ] && pty_ours "$s" "$dst" && cp "$src" "$dst"; done < <(gh_targets "$s")
    return 0
}
gh_conf_file() { local f; for f in "$gh_dir/config.ghostty" "$gh_dir/config"; do if [ -f "$f" ]; then echo "$f"; return 0; fi; done; return 0; }   # the user's main config
gh_line_in() { grep -qE '^[[:space:]]*config-file[[:space:]]*=[[:space:]]*"?\??candy-for-gnome\.conf"?[[:space:]]*$' "$1" 2>/dev/null; }
gh_link_ours() { [ -L "$gh_link" ] && case "$(readlink "$gh_link")" in "$gh_data"/*) return 0 ;; esac; return 1; }
gh_remove() {    # remove only files that carry our marker and the link when it points at this scheme's pair file; the user's config is never edited
    local s="$1" src dst conf
    gh_present || return 0
    while IFS='|' read -r src dst; do
        [ -e "$dst" ] || continue
        if pty_ours "$s" "$dst"; then rm -f "$dst"; echo "Removed $dst"; else echo "Left $dst alone (not installed by candy-for-gnome)." >&2; fi
    done < <(gh_targets "$s")
    if gh_link_ours && [ "$(readlink "$gh_link")" = "$gh_data/$s.conf" ]; then
        rm -f "$gh_link"; echo "Removed $gh_link"
        conf=$(gh_conf_file)
        if [ -n "$conf" ] && gh_line_in "$conf"; then echo "Ghostty: your $conf still has the line below; it is harmless (the ? ignores a missing file), delete it when you like:"; echo "  $gh_line"; fi
    fi
    return 0
}
gh_switch() {    # point Ghostty at the scheme: link the pair file, ask once about the include line, print the reload hint
    local s="$1" conf a first
    if ! gh_present; then echo "Ghostty: no config directory ($gh_dir), so nothing was set up for it."; return 0; fi
    first=$(gh_themes "$s" | head -n1)
    if [ -z "$first" ] || ! pty_ours "$s" "$gh_data/$s.conf" || ! pty_ours "$s" "$gh_dir/themes/$first"; then
        echo "Ghostty theme not applied: the installed copy of $s is missing or not ours."; return 0
    fi
    if [ ! -e "$gh_link" ] && [ ! -L "$gh_link" ] || gh_link_ours; then ln -sfn "$gh_data/$s.conf" "$gh_link"
    else
        a=n
        if [ "${FORCE:-}" = 1 ]; then a=y
        elif [ "$tty_in" = 1 ]; then read -r -u 3 -p "$gh_link exists and was not created by candy-for-gnome. Replace it with a link to the theme? [y/N] " a || a=n
        else echo "Refused: $gh_link exists and was not created by candy-for-gnome; left alone (FORCE=1 replaces it, or run in a terminal to be asked)." >&2; return 0; fi
        case "$a" in [yY]*) rm -rf "$gh_link"; ln -s "$gh_data/$s.conf" "$gh_link" ;; *) echo "Left $gh_link alone." >&2; return 0 ;; esac
    fi
    echo "Ghostty theme is now $s (follows the system light/dark setting; $gh_link)."
    conf=$(gh_conf_file)
    if [ -n "$conf" ] && gh_line_in "$conf"; then :
    elif [ -z "$conf" ]; then
        app_create "$gh_dir/config.ghostty" '#' "$gh_line" || { echo "Ghostty: could not create $gh_dir/config.ghostty. To use the theme, put this line in your Ghostty config:"; echo "  $gh_line"; }
    elif [ "$tty_in" = 1 ]; then
        read -r -u 3 -p "Add the line '$gh_line' to $conf so Ghostty loads the theme (no other line is touched; the theme line it includes overrides a theme= line there)? [y/N] " a || a=n
        case "$a" in
            [yY]*) [ -z "$(tail -c1 "$conf")" ] || echo >> "$conf"; echo "$gh_line" >> "$conf"; echo "Added the line to $conf." ;;
            *) echo "Left $conf alone. To use the theme, add this line yourself:"; echo "  $gh_line" ;;
        esac
    else
        echo "Ghostty: not editing $conf without a terminal. To use the theme, add this line to it:"; echo "  $gh_line"
    fi
    echo "Ghostty has no auto-reload: press ctrl+shift+, (reload_config) in open Ghostty windows."
}
gh_adwaita() {   # switch-theme Adwaita: retarget the managed include link to the neutral pair file (the user's config is never touched, nothing is created when there is no managed link)
    gh_present && gh_link_ours || return 0
    local src dst
    while IFS='|' read -r src dst; do pty_may_touch adwaita Replace "$dst" || return 0; mkdir -p "$(dirname "$dst")"; cp "$src" "$dst"; done < <(gh_targets adwaita)
    ln -sfn "$gh_data/adwaita.conf" "$gh_link"
    echo "Ghostty is now neutral (its include link points at an empty config, so Ghostty uses its own theme; $gh_link)."
    echo "Ghostty has no auto-reload: press ctrl+shift+, (reload_config) in open Ghostty windows."
}
gh_status() {    # a line for list-themes, only when the Ghostty config directory exists
    gh_present || return 0
    local t="none" conf; gh_link_ours && t=$(basename "$(readlink "$gh_link")" .conf); conf=$(gh_conf_file)
    echo "Ghostty ($gh_dir): theme $t; include line: $([ -n "$conf" ] && gh_line_in "$conf" && echo present || echo "not in the config")"
}

