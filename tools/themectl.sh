# ---- Flatpak access (themes and icons: grant after switch-theme, undo after the last removal) -------------------
# shellcheck disable=SC2088  # the tilde is literal on purpose: flatpak stores and shows the entry as ~/.themes
fp_paths=(xdg-config/gtk-3.0:ro xdg-config/gtk-4.0:ro xdg-data/icons:ro '~/.themes:ro')   # literal tilde, as flatpak stores it; the only entries candy-for-gnome ever manages
fp_state="$state/flatpak-overrides"
fp_have() { flatpak override --user --show 2>/dev/null | sed -n 's/^filesystems=//p' | tr ';' '\n' | grep -vx '' || true; }
fp_cmd_add() { local c="flatpak override --user" p; for p in "$@"; do c="$c --filesystem=$p"; done; echo "$c"; }
fp_cmd_del() { local c="flatpak override --user" p; for p in "$@"; do c="$c --nofilesystem=${p%:*}"; done; echo "$c"; }
fp_check() {   # after switch-theme: offer the missing read-only entries
    command -v flatpak >/dev/null 2>&1 || return 0
    local have p a miss=()
    have=$(fp_have)
    for p in "${fp_paths[@]}"; do printf '%s\n' "$have" | grep -qxF -- "$p" || miss+=("$p"); done
    [ "${#miss[@]}" -gt 0 ] || return 0
    echo "Flatpak sandbox: no global read-only access yet to: ${miss[*]}"
    if [ "$tty_in" = 1 ]; then
        read -r -u 3 -p "Flatpak apps (for example Calculator, Text Editor) cannot see your themes. Allow read-only access to these folders for all Flatpaks? [y/N] " a || a=n
        case "$a" in
            [yY]*) for p in "${miss[@]}"; do
                       if flatpak override --user --filesystem="$p"; then state_add_line "$fp_state" "$p"; else echo "Could not grant $p." >&2; fi
                   done; echo "Granted; restart the Flatpak apps. candy-for-gnome removes exactly these again when you remove the last theme and icon set." ;;
            *) echo "Left the Flatpak sandbox alone." ;;
        esac
    else
        echo "Not changing the Flatpak sandbox without a terminal. To allow it, run:"; echo "  $(fp_cmd_add "${miss[@]}")"
        echo "  (or run switch-theme in a terminal and answer y; candy-for-gnome then records what it added and removes only that later)"
    fi
}
state_add_line() { mkdir -p "$(dirname "$1")"; grep -qxF -- "$2" "$1" 2>/dev/null || echo "$2" >> "$1"; }
any_marked() {   # is any theme or icon set of this repo (marker file) installed? (both destinations, whatever kind runs)
    local d
    for d in "${THEMES_DEST:-$HOME/.themes}" "${ICONS_DEST:-${XDG_DATA_HOME:-$HOME/.local/share}/icons}"; do
        [ -d "$d" ] && find "$d" -mindepth 2 -maxdepth 2 -name "$marker" 2>/dev/null | grep -q . && return 0
    done
    return 1
}
fp_undo() {    # after remove: when nothing of ours is installed any more, offer to remove the recorded entries
    [ -s "$fp_state" ] || return 0
    any_marked && return 0
    local ents=() p a; while read -r p; do [ -n "$p" ] && ents+=("$p"); done < "$fp_state"
    [ "${#ents[@]}" -gt 0 ] || return 0
    if ! command -v flatpak >/dev/null 2>&1; then echo "Flatpak not found; the record $fp_state still lists: ${ents[*]}"; return 0; fi
    if [ "$tty_in" = 1 ]; then
        read -r -u 3 -p "Remove the Flatpak read access that candy-for-gnome added? [y/N] " a || a=n
        case "$a" in
            [yY]*) for p in "${ents[@]}"; do flatpak override --user --nofilesystem="${p%:*}" || echo "Could not remove $p." >&2; done
                   rm -f "$fp_state"; echo "Removed the Flatpak access candy-for-gnome had added (${ents[*]})." ;;
            *) echo "Left the Flatpak access in place." ;;
        esac
    else
        echo "candy-for-gnome added Flatpak read access that nothing uses any more. To remove exactly that, run:"; echo "  $(fp_cmd_del "${ents[@]}")"
        echo "  (then delete $fp_state, or run remove-theme in a terminal and answer y)"
    fi
}

# ---- actions -------------------------------------------------------------------------------------
skipped=(); installed_n=0
was_skipped() { local s; for s in "${skipped[@]}"; do [ "$s" = "$1" ] && return 0; done; return 1; }
copy_folder() {  # replace folder $1 of item $2 in dest: remove the set's folder, then copy the fresh one (never merge); 1 = guard said no
    local f="$1" it="$2" c
    mkdir -p "$dest"
    if ! may_touch "$dest/$f" "$(src_index "$it" "$f")" Replace; then skipped+=("$f"); return 1; fi
    mark_old=$(marker_read "$dest/$f" installed_at)
    rm -rf "${dest:?}/$f"
    if [ "$kind" = themes ]; then
        cp -a "$troot/$it/gtk/$f" "$dest/$f"
        # the stock assets are stored once in the repo (assets/gtk-3.0, assets/gtk-4.0): installed themes get real copies
        for v in gtk-3.0 gtk-4.0; do
            if [ -d "$dest/$f/$v" ] && [ -d "$root/assets/$v" ]; then mkdir -p "$dest/$f/$v/assets"; cp -a "$root/assets/$v/." "$dest/$f/$v/assets/"; fi
        done
    else
        c=$(clone_of "${i_src[$it]}")
        case "${src_layout[${i_src[$it]}]}" in
            top) cp -a "$c/${i_dir[$it]}" "$dest/$f" ;;
            root) mkdir -p "$dest/$f"; (cd "$c" && tar cf - --exclude=./.git --exclude=./.github --exclude='./preview*' --exclude='./README*' --exclude=./update.sh --exclude=./images --exclude=./CONTRIBUTING.md --exclude=./.gitignore .) | tar xf - -C "$dest/$f" ;;
            script|script-t) cp -a "$build_dir/$f" "$dest/$f" ;;
        esac
        gtk-update-icon-cache -q -f -t "$dest/$f" 2>/dev/null || true
    fi
    mark_dir "$dest/$f" "$it" "$f"; mark_old=""
    if [ "$kind" = themes ]; then apply_accent "$it" "$(current_accent "$it")" "$f"; fi
    installed_n=$((installed_n+1)); echo "Installed $f -> $dest/$f"
}
copy_item() {
    local f h b mine=0
    prepare_item "$1" || return 1
    while read -r f; do if is_ours "$dest/$f" "$(src_index "$1" "$f")"; then mine=1; fi; done < <(folders_of "$1")
    while read -r f; do copy_folder "$f" "$1" || true; done < <(folders_of "$1")
    if [ -n "$build_dir" ]; then   # hidden shared bases the build produced (Fluent's .Fluent-base ...): replaced too
        for h in "$build_dir"/.[!.]*; do
            [ -d "$h" ] || continue; b=$(basename "$h")
            mark_old=$(marker_read "$dest/$b" installed_at)
            # a base is ours when marked, or when one of this set's own folders was ours before this run (it links into the base)
            if [ -e "$dest/$b" ] && ! marker_present "$dest/$b" && [ "$mine" -eq 1 ]; then rm -rf "${dest:?}/$b"
            elif ! may_touch "$dest/$b" "" Replace; then continue; else rm -rf "${dest:?}/$b"; fi
            cp -a "$h" "$dest/$b"; mark_dir "$dest/$b" "$1" "$b"; mark_old=""; echo "Installed $b (shared base)"
        done
    fi
    finish_item
}
refresh_for() {  # icons: refresh the clones of the sources of the named sets ($@)
    local n seen=" "
    for n in "$@"; do case "$seen" in *" ${i_src[$n]} "*) ;; *) seen="$seen${i_src[$n]} "; refresh_source "${i_src[$n]}" ;; esac; done
}
current_value() {  # the value the desktop currently uses (theme or icon set)
    if [ "$kind" = themes ]; then gsettings get org.gnome.desktop.interface gtk-theme 2>/dev/null | tr -d "'" || true
    else gsettings get org.gnome.desktop.interface icon-theme 2>/dev/null | tr -d "'" || true; fi
}
# resolve $want to an index, or explain
resolve() { local art=a; [ "$kind" = icons ] && art=an; index_of "$want" || { echo "'$want' is not $art $noun here. Available: ${items[*]}" >&2; exit 1; }; }

set_ini() {  # set_ini KEY VALUE: rewrite the key in the GTK settings.ini files that already have it
    local f; for f in "$cfg/gtk-3.0/settings.ini" "$cfg/gtk-4.0/settings.ini"; do
        if [ -f "$f" ] && grep -q "^$1=" "$f"; then sed -i "s|^$1=.*|$1=$2|" "$f"; fi
    done
}

# ---- grouped icon menus (a terminal only; named sets, pipes and the numbered fallback keep the flat lists) --------------------------------------
# icons_grouped: the family -> colour -> style pickers are used when a picker can really run (gum, or the built-in one on a terminal).
# Families are the registry's sources, colours are the items of a script source (the registry's variants), styles are the folders of one colour
# (standard, -dark, -light); a family with one installed set, a colour with one installed folder skip their step. Nothing here changes what is
# installed, copied or switched: the steps only narrow down to the same items and folder names the flat lists use.
icons_grouped() { [ "$kind" = icons ] && { [ "$(pick_handler)" = gum ] || { [ -t 0 ] && [ -t 2 ] && [ -r /dev/tty ]; }; }; }
fam_name() { local w out=""; for w in ${1//-/ }; do out="$out ${w^}"; done; echo "${out# }"; }   # display name of a source key: gruvbox-plus -> Gruvbox Plus
fam_script() { case "${src_layout[$1]:-}" in script|script-t) return 0 ;; *) return 1 ;; esac; }
fam_members() {   # fam_members FAMILY [installed]: fam_idx = item indexes of the family (registry order), only the installed ones with "installed"
    fam_idx=(); local j
    for j in "${!items[@]}"; do
        [ "${i_src[${items[j]}]:-}" = "$1" ] || continue
        if [ "${2:-}" = installed ]; then is_installed "${items[j]}" || continue; fi
        fam_idx+=("$j")
    done
}
colour_label() { if [ "${i_var[$1]:-}" = standard ]; then echo "default"; else echo "${i_var[$1]:-$1}"; fi; }   # colour name of item $1 (the plain default is "default")
has_folder() { local f; while read -r f; do [ "$f" = "$2" ] && return 0; done < <(folders_of "$1"); return 1; }   # has_folder ITEM FOLDER
installed_folders() { local f; while read -r f; do if [ -e "$dest/$f" ]; then echo "$f"; fi; done < <(folders_of "$1"); }
style_label() { case "$2" in "$1") echo standard ;; "$1-dark") echo dark ;; "$1-light") echo light ;; *) echo "$2" ;; esac; }   # style_label ITEM FOLDER
pick_label() {   # pick_label HEADER CURSOR_INDEX LABEL...: one choice among plain labels (the pickers index into labels[]), pick_idx = index or empty when cancelled
    local header="$1" cur="$2"; shift 2
    local savedl=("${labels[@]}") ls=("$@") idx=() i
    labels=("${ls[@]}"); for i in "${!ls[@]}"; do idx+=("$i"); done
    local sw_sv=("${swatch[@]}") sw_wsv=("${swatch_w[@]}"); sw_clear
    if sw_ok && [ "${#pl_hex[@]}" -gt 0 ]; then for i in "${!ls[@]}"; do sw_set "$i" "${pl_hex[i]:-}"; done; fi
    tui_cur=$cur; pick_keep_order=1; choose_one "$header" "${idx[@]}"; pick_keep_order=0; tui_cur=0
    pick_idx="${pick:-}"; labels=("${savedl[@]}"); swatch=("${sw_sv[@]}"); swatch_w=("${sw_wsv[@]}"); pl_hex=()
}
pick_many_label() {   # pick_many_label HEADER: checklist over pm_labels[] with pm_on[] ticks; pm_chosen = the ticked indexes
    local header="$1" savedl=("${labels[@]}") saved_on=() i k idx=()
    for k in "${!on[@]}"; do saved_on[k]="${on[k]}"; done
    labels=("${pm_labels[@]}"); on=(); for i in "${!pm_labels[@]}"; do on[i]="${pm_on[i]:-0}"; idx+=("$i"); done
    local sw_sv=("${swatch[@]}") sw_wsv=("${swatch_w[@]}"); sw_clear
    if sw_ok && [ "${#pl_hex[@]}" -gt 0 ]; then for i in "${!pm_labels[@]}"; do sw_set "$i" "${pl_hex[i]:-}"; done; fi
    choose_many "$header" "${idx[@]}"
    pm_chosen=("${chosen[@]}")
    swatch=("${sw_sv[@]}"); swatch_w=("${sw_wsv[@]}"); pl_hex=()
    labels=("${savedl[@]}"); on=(); for k in "${!saved_on[@]}"; do on[k]="${saved_on[k]}"; done
}
icons_pick_switch() {   # family, then colour, then style: sets i (item index) and sw_target (the folder to switch to)
    local cur n j f lab fk fkeys=(Adwaita) flabels=("$adw_label") curf=0 ls=() ci=0 c k sf=()
    cur=$(current_value)
    if [ "$cur" = Adwaita ]; then flabels[0]="$adw_label  (current)"; fi
    for n in "${src_names[@]}"; do
        fam_members "$n" installed; [ "${#fam_idx[@]}" -gt 0 ] || continue
        lab=$(fam_name "$n")
        for j in "${fam_idx[@]}"; do if has_folder "${items[j]}" "$cur"; then lab="$lab  (current)"; curf=${#fkeys[@]}; fi; done
        fkeys+=("$n"); flabels+=("$lab")
    done
    pick_label "Switch to which icon family?" "$curf" "${flabels[@]}"
    [ -n "$pick_idx" ] || { echo "Cancelled."; exit 0; }
    fk="${fkeys[pick_idx]}"
    if [ "$fk" = Adwaita ]; then i=$(index_of Adwaita); sw_target=Adwaita; return 0; fi
    fam_members "$fk" installed; local mem=("${fam_idx[@]}")
    if [ "${#mem[@]}" -gt 1 ]; then
        ls=(); ci=0
        for k in "${!mem[@]}"; do
            j="${mem[k]}"; if fam_script "$fk"; then lab=$(colour_label "${items[j]}"); else lab="${items[j]}"; fi
            if has_folder "${items[j]}" "$cur"; then lab="$lab  (current)"; ci=$k; fi
            ls+=("$lab"); if fam_script "$fk"; then pl_hex[k]=$(icon_hex_of "${i_var[${items[j]}]:-}"); fi
        done
        if fam_script "$fk"; then c="$(fam_name "$fk") colour"; else c="$(fam_name "$fk") set"; fi
        pick_label "Switch to which $c?" "$ci" "${ls[@]}"
        [ -n "$pick_idx" ] || { echo "Cancelled."; exit 0; }
        i="${mem[pick_idx]}"
    else i="${mem[0]}"; fi
    sw_target="${items[i]}"
    if fam_script "$fk"; then
        mapfile -t sf < <(installed_folders "${items[i]}")
        if [ "${#sf[@]}" -gt 1 ]; then
            ls=(); ci=0
            for k in "${!sf[@]}"; do lab=$(style_label "${items[i]}" "${sf[k]}"); if [ "${sf[k]}" = "$cur" ]; then lab="$lab  (current)"; ci=$k; fi; ls+=("$lab"); done
            pick_label "Switch to which style of $(fam_name "$fk") $(colour_label "${items[i]}")?" "$ci" "${ls[@]}"
            [ -n "$pick_idx" ] || { echo "Cancelled."; exit 0; }
            sw_target="${sf[pick_idx]}"
        elif [ "${#sf[@]}" -eq 1 ]; then sw_target="${sf[0]}"; fi
    fi
}
icon_folder_item() {   # icon_folder_item NAME: "<item index>|<folder>" when NAME is an installed style folder (Tela-dark, WhiteSur-nord-light) of an installed set
    local j f
    for j in "${!items[@]}"; do
        is_adwaita "${items[j]}" && continue
        is_installed "${items[j]}" || continue
        while read -r f; do if [ "$f" = "$1" ] && [ -e "$dest/$f" ]; then echo "$j|$f"; return 0; fi; done < <(folders_of "${items[j]}")
    done
    return 1
}
icons_pick_many() {   # icons_pick_many install|remove: families first, then the colours or sets of each ticked family; sets chosen (item indexes)
    local mode="$1" n lab ni fkeys=() j k fam_ticked=() c
    pm_labels=(); pm_on=()
    for n in "${src_names[@]}"; do
        fam_members "$n"; [ "${#fam_idx[@]}" -gt 0 ] || continue
        fam_members "$n" installed; ni=${#fam_idx[@]}
        if [ "$mode" = remove ] && [ "$ni" -eq 0 ]; then continue; fi
        lab=$(fam_name "$n"); if [ "$mode" = install ] && [ "$ni" -gt 0 ]; then lab="✓ $lab"; fi
        fkeys+=("$n"); pm_labels+=("$lab")
    done
    [ "${#fkeys[@]}" -gt 0 ] || { chosen=(); return 0; }
    if [ "$mode" = install ]; then pick_many_label "Icon families to install into $dest"; else pick_many_label "Icon families to remove from $dest"; fi
    for k in "${pm_chosen[@]}"; do fam_ticked+=("${fkeys[k]}"); done
    local out=()
    for n in "${fam_ticked[@]}"; do
        if [ "$mode" = remove ]; then fam_members "$n" installed; else fam_members "$n"; fi
        local mem=("${fam_idx[@]}")
        if [ "${#mem[@]}" -eq 1 ]; then out+=("${mem[0]}"); continue; fi
        pm_labels=(); pm_on=()
        for k in "${!mem[@]}"; do
            j="${mem[k]}"; if fam_script "$n"; then lab=$(colour_label "${items[j]}"); else lab="${items[j]}"; fi
            if [ "$mode" = install ] && is_installed "${items[j]}"; then lab="✓ $lab"; fi
            pm_labels+=("$lab"); if fam_script "$n"; then pl_hex[k]=$(icon_hex_of "${i_var[${items[j]}]:-}"); fi
        done
        if fam_script "$n"; then c="colors"; else c="sets"; fi
        if [ "$mode" = install ]; then pick_many_label "$(fam_name "$n") $c to install into $dest"; else pick_many_label "$(fam_name "$n") $c to remove from $dest"; fi
        for k in "${pm_chosen[@]}"; do out+=("${mem[k]}"); done
    done
    chosen=("${out[@]}")
}

# ---- Adwaita (GNOME default): `switch-theme Adwaita` hands the look back to GNOME and the tools ---------------------------------------------
# No file of a user is ever edited or deleted. GNOME keys are reset or set to the stock value; every MANAGED link (made by this installer) is
# retargeted to a neutral file shipped in adwaita/ (installed like a scheme's files, marker `candy-for-gnome: adwaita`), exactly the way a switch
# between schemes retargets it, so the user's config keeps pointing at the same link and `switch-theme <scheme>` points it back. Links that do
# not exist are not created, and nothing is asked.
adw_reset_dconf() {  # adw_reset_dconf KEY: reset a key through gsettings-independent dconf (the key paths of Ptyxis, Text Editor, Builder, User Themes)
    command -v dconf >/dev/null 2>&1 && dconf reset "$1" 2>/dev/null
}
adw_shell() {
    local done_=0
    if gsettings list-schemas 2>/dev/null | grep -qx org.gnome.shell.extensions.user-theme; then gsettings reset org.gnome.shell.extensions.user-theme name && done_=1
    elif adw_reset_dconf /org/gnome/shell/extensions/user-theme/name; then done_=1; fi
    if [ "$done_" = 1 ]; then echo "Shell theme is now the GNOME default (the User Themes key was reset; reload it by logging out and in, or toggling the User Themes extension)."
    else echo "Could not reset the Shell theme: neither gsettings nor dconf could write the User Themes key."; fi
}
adw_libadwaita() {   # remove the libadwaita file only when candy-for-gnome generated it; a backup of the user's own file (.bak) is put back, never lost
    local t="$cfg/gtk-4.0/gtk.css"
    [ -e "$t" ] || return 0
    if ! grep -q "libadwaita-gen.py" "$t" 2>/dev/null; then echo "$t is not generated by candy-for-gnome; left alone."; return 0; fi
    if [ -e "$t.bak" ]; then cp -L "$t.bak" "$t"; echo "Updated $t (your own file from $t.bak is back; the backup stays)."
    else rm -f "$t"; echo "Removed $t (the libadwaita file candy-for-gnome had generated)."; fi
}
adw_ptyxis() {   # reset the palette key on the same profiles switch-theme sets (the default one and those with a key): the key's own default is Ptyxis's stock palette
    local uuids def u sel=() n=0
    command -v dconf >/dev/null 2>&1 || { echo "Ptyxis palette not changed: dconf not found."; return 0; }
    uuids=$(dconf read /org/gnome/Ptyxis/profile-uuids 2>/dev/null | dq || true)
    def=$(dconf read /org/gnome/Ptyxis/default-profile-uuid 2>/dev/null | dq | head -n1 || true)
    [ -n "$def" ] || def=$(printf '%s\n' "$uuids" | head -n1)
    [ -n "$def" ] || { echo "Ptyxis palette not changed: no Ptyxis profile found."; return 0; }
    sel=("$def")
    for u in $uuids; do [ "$u" = "$def" ] && continue; [ -n "$(dconf read "/org/gnome/Ptyxis/Profiles/$u/palette" 2>/dev/null || true)" ] && sel+=("$u"); done
    for u in "${sel[@]}"; do dconf reset "/org/gnome/Ptyxis/Profiles/$u/palette" && n=$((n+1)); done
    echo "Ptyxis palette is now the Ptyxis default (the palette key was reset on $n profile(s); candy-for-gnome does not record the previous one)."
}
adw_gsv_flatpak() {  # adw_gsv_flatpak APP SCHEMA KEY LABEL: reset the key in the app's own sandbox store and report what it reads back
    local app="$1" schema="$2" key="$3" label="$4" got
    flatpak run --command=gsettings "$app" reset "$schema" "$key" </dev/null >/dev/null 2>&1 || true
    got=$(flatpak run --command=gsettings "$app" get "$schema" "$key" </dev/null 2>/dev/null | tr -d "'") || got=""
    echo "$label (Flatpak) style scheme is now the stock default (${got:-unknown})."
}
adw_gsv() {   # Text Editor and Builder: reset the style-scheme key (the stock default, not a named scheme); the installed style files stay
    if gsv_flatpak org.gnome.TextEditor; then adw_gsv_flatpak org.gnome.TextEditor org.gnome.TextEditor style-scheme "Text Editor"; fi
    if ! gsv_flatpak org.gnome.TextEditor || gsettings list-schemas 2>/dev/null | grep -qx org.gnome.TextEditor; then
        if adw_reset_dconf /org/gnome/TextEditor/style-scheme; then echo "Text Editor style scheme is now the stock default (the key was reset)."; fi
    fi
    if gsv_flatpak org.gnome.Builder; then adw_gsv_flatpak org.gnome.Builder org.gnome.builder.editor style-scheme-name "Builder"; fi
    if gsettings list-schemas 2>/dev/null | grep -qx org.gnome.builder.editor; then
        if adw_reset_dconf /org/gnome/builder/editor/style-scheme-name; then echo "Builder style scheme is now the stock default (the key was reset)."; fi
    fi
    return 0
}
adwaita_theme_switch() {
    gsettings set org.gnome.desktop.interface gtk-theme Adwaita; set_ini gtk-theme-name Adwaita
    echo "GTK theme is now Adwaita (the GNOME default; your light/dark preference is unchanged)."
    adw_shell
    adw_libadwaita
    pty_cleanup; adw_ptyxis; adw_gsv
    gh_adwaita; app_adwaita
    echo "Restart GTK apps to pick up the new theme."
}

case "$action" in
    list)
        load_items; add_adwaita
        for i in "${!items[@]}"; do
            ac=""; if [ "$kind" = themes ] && ! is_adwaita "${items[i]}"; then ac="  [accent: $(current_accent "${items[i]}")]"; fi
            if is_adwaita "${items[i]}"; then if [ "$(current_value)" = Adwaita ]; then echo "✓ ${labels[i]}"; else echo "  ${labels[i]}"; fi
            elif is_installed "${items[i]}"; then echo "✓ ${labels[i]}$ac"; else echo "  ${labels[i]}"; fi
        done
        if [ "$kind" = themes ]; then gh_status; apps_status; fi ;;

    install)
        just_installed=()
        load_items
        [ "${#items[@]}" -gt 0 ] || { echo "No ${noun}s found"; exit 1; }
        if [ -n "$want" ]; then
            i=$(resolve); chosen=("$i")
        else
            # nothing is pre-ticked (themes and icons): an installed set is only marked with a check mark, and installing it again refreshes it
            for i in "${!items[@]}"; do on[i]=0; done
            if [ "$kind" = icons ] && icons_grouped; then icons_pick_many install
            else
                if [ "$kind" = icons ]; then for i in "${!items[@]}"; do if is_installed "${items[i]}"; then labels[i]="✓ ${labels[i]}"; fi; done; fi
                choose_many "${noun^}s to install into $dest" "${!items[@]}"
            fi
        fi
        [ "${#chosen[@]}" -gt 0 ] || { nothing_selected; exit 0; }
        names=(); for i in "${chosen[@]}"; do names+=("${items[i]}"); done
        if [ "$kind" = icons ]; then refresh_for "${names[@]}"; fi   # icons: clone or refresh only the sources of the chosen sets
        for nm in "${names[@]}"; do
            if [ "$kind" = icons ] && [ ! -d "$(clone_of "${i_src[$nm]}")/.git" ]; then echo "Skipping $nm: its source ${i_src[$nm]} is not available." >&2; continue; fi
            before=$installed_n; copy_item "$nm"; if [ "$installed_n" -gt "$before" ]; then just_installed+=("$nm"); fi
            if [ "$kind" = themes ]; then pty_cleanup; gsv_install "$nm"; gh_install "$nm"; app_install "$nm"; fi; done
        if [ "$installed_n" -eq 0 ]; then echo "Nothing was installed (see the messages above)."
        else
            if [ "$kind" = themes ]; then echo "Next: run switch-theme to use it."; else echo "Next: run switch-icon to use it."; fi
            after_install_switch "${just_installed[@]}"
        fi ;;

    update)
        # themes: git fetch + pull --ff-only in this checkout; icons: refresh the clones of the installed sets' sources.
        # Then every installed set's folders are removed and copied fresh (the remembered accent is re-applied).
        load_items; n=0; inst=()
        for i in "${!items[@]}"; do if is_installed "${items[i]}"; then inst+=("${items[i]}"); fi; done
        if [ "$kind" = icons ]; then refresh_for "${inst[@]}"; else sync_themes; fi
        for nm in "${inst[@]}"; do
            if [ "$kind" = icons ] && [ ! -d "$(clone_of "${i_src[$nm]}")/.git" ]; then echo "Skipping $nm: its source ${i_src[$nm]} is not available." >&2; continue; fi
            if [ "$kind" = icons ]; then copy_item "$nm"; n=$((n+1))
            else while read -r f; do if [ -e "$dest/$f" ] && copy_folder "$f" "$nm"; then n=$((n+1)); fi; done < <(folders_of "$nm"); pty_cleanup; gsv_refresh "$nm"; gh_refresh "$nm"; app_refresh "$nm"; fi
        done
        if [ "$kind" = themes ]; then gh_refresh adwaita; app_refresh adwaita; fi   # the neutral files of switch-theme Adwaita, only where they exist and are ours
        [ "$n" -gt 0 ] || echo "None of the ${noun}s from this source is installed in $dest." ;;

    remove)
        load_items; inst=()
        for i in "${!items[@]}"; do if is_installed "${items[i]}"; then inst+=("$i"); fi; done
        [ "${#inst[@]}" -gt 0 ] || { echo "No ${noun}s from this source are installed in $dest."; exit 0; }
        if [ -n "$want" ]; then
            i=$(resolve); is_installed "${items[i]}" || { echo "'$want' is not installed."; exit 1; }
            chosen=("$i")
        else
            for i in "${!items[@]}"; do on[i]=0; done
            if icons_grouped; then icons_pick_many remove; else choose_many "${noun^}s to remove from $dest" "${inst[@]}"; fi
        fi
        [ "${#chosen[@]}" -gt 0 ] || { nothing_selected; exit 0; }
        cur=$(current_value); bases=""
        if [ "$kind" = icons ]; then for i in "${chosen[@]}"; do bases+=$'\n'"$(shared_bases "${items[i]}")"; done; fi
        for i in "${chosen[@]}"; do
            while read -r f; do
                if [ -e "$dest/$f" ] || [ -L "$dest/$f" ]; then
                    may_touch "$dest/$f" "$(src_index "${items[i]}" "$f")" Remove || continue
                    rm -rf "${dest:?}/$f"; echo "Removed $dest/$f"
                    if [ "$f" = "$cur" ]; then echo "  note: $f is the one currently in use; run switch to choose another."; fi
                fi
            done < <(folders_of "${items[i]}")
            if [ "$kind" = themes ] && ! is_installed "${items[i]}"; then state_del "$state/accents" "${items[i]}"; fi
            if [ "$kind" = themes ]; then pty_cleanup; gsv_remove "${items[i]}"; gh_remove "${items[i]}"; app_remove "${items[i]}"; fi
        done
        # shared hidden base dirs (Fluent): remove one only when no remaining installed set links into it
        if [ "$kind" = icons ]; then
            still=""; for i in "${!items[@]}"; do if is_installed "${items[i]}"; then still+=$'\n'"$(shared_bases "${items[i]}")"; fi; done
            for b in $bases; do
                if ! printf '%s\n' "$still" | grep -qxF -- "$b" && [ -d "$dest/$b" ] && may_touch "$dest/$b" "" Remove; then rm -rf "${dest:?}/$b"; echo "Removed $dest/$b (shared base, no longer used)"; fi
            done
        fi
        fp_undo ;;

    switch)
        load_items; add_adwaita; inst=()
        case "${want,,}" in adwaita) want=Adwaita ;; esac
        for i in "${!items[@]}"; do if is_installed "${items[i]}"; then inst+=("$i"); fi; done
        [ "${#inst[@]}" -gt 0 ] || { echo "No ${noun}s from this source are installed; install one first."; exit 1; }
        sw_target=""
        if [ -n "$want" ]; then
            if [ "$kind" = icons ] && ! index_of "$want" >/dev/null && fi_=$(icon_folder_item "$want"); then i="${fi_%%|*}"; sw_target="${fi_#*|}"
            else i=$(resolve); is_installed "${items[i]}" || { echo "'$want' is not installed; install it first."; exit 1; }; fi
        elif icons_grouped; then icons_pick_switch
        else
            choose_one "Switch to which $noun?" "${inst[@]}"; i="$pick"
            [ -n "$i" ] || { echo "Cancelled."; exit 0; }
        fi
        [ -n "$sw_target" ] || sw_target="${items[i]}"
        if [ "$kind" = themes ] && is_adwaita "${items[i]}"; then
            adwaita_theme_switch; exit 0
        fi
        if [ "$kind" = themes ]; then
            # accent: argument, else the submenu; copy the scheme's folders afresh (clean) and re-apply it
            load_accents "${items[i]}"
            if [ -n "$accent_arg" ]; then
                printf '%s\n' "${acc_names[@]}" | grep -qx "$accent_arg" || { echo "'$accent_arg' is not an accent of ${items[i]}. Available: ${acc_names[*]}" >&2; exit 1; }
                accent_pick="$accent_arg"
            else choose_accent "${items[i]}"; fi
            if [ -n "$accent_pick" ]; then state_set "$state/accents" "${items[i]}" "$accent_pick"; fi
            copy_item "${items[i]}"; pty_cleanup; gsv_install "${items[i]}"; gh_install "${items[i]}"; app_install "${items[i]}"
            [ -z "$accent_pick" ] || echo "Accent: $accent_pick."
        fi
        if [ "$kind" = icons ]; then
            gsettings set org.gnome.desktop.interface icon-theme "$sw_target"
            set_ini gtk-icon-theme-name "$sw_target"
            if is_adwaita "${items[i]}"; then echo "Icon theme is now Adwaita (the GNOME default; no icon folder was installed or removed)."
            else echo "Icon theme is now $sw_target."; fi
        else
            sc="${items[i]}"; gtk=""; shell_d=""; shell_l=""
            while read -r f; do
                case "$f" in
                    *-Shell-Dark) shell_d="$f" ;;
                    *-Shell-Light) shell_l="$f" ;;
                    *-Shell-*) ;;
                    *) [ -n "$gtk" ] || gtk="$f" ;;
                esac
            done < <(folders_of "$sc")
            if [ -n "$gtk" ] && was_skipped "$gtk"; then echo "Not switching the GTK theme: $gtk was left alone (not installed by candy-for-gnome)."; gtk=""; fi
            if [ -n "$gtk" ]; then
                gsettings set org.gnome.desktop.interface gtk-theme "$gtk"; set_ini gtk-theme-name "$gtk"
                echo "GTK theme is now $gtk."
            fi
            shell="${shell_d:-$shell_l}"     # a light-only scheme has no Dark Shell theme
            if ! gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null | grep -qi dark; then shell="${shell_l:-$shell_d}"; fi
            if [ -n "$shell" ] && was_skipped "$shell"; then echo "Not switching the Shell theme: $shell was left alone (not installed by candy-for-gnome)."; shell=""; fi
            if [ -n "$shell" ]; then
                shell_done=0
                if gsettings list-schemas 2>/dev/null | grep -qx org.gnome.shell.extensions.user-theme; then
                    gsettings set org.gnome.shell.extensions.user-theme name "$shell" && shell_done=1
                elif command -v dconf >/dev/null 2>&1; then
                    # The User Themes extension is normally installed per user, so its schema is not in the system schema dirs and
                    # gsettings does not list it: write the key directly.
                    dconf write /org/gnome/shell/extensions/user-theme/name "'$shell'" && shell_done=1
                fi
                if [ "$shell_done" -eq 1 ]; then echo "Shell theme is now $shell (reload it by logging out and in, or toggling the User Themes extension)."
                else echo "Could not set the Shell theme: neither gsettings nor dconf could write the User Themes key."; fi
                if command -v gnome-extensions >/dev/null 2>&1 && ! gnome-extensions list --enabled 2>/dev/null | grep -q '^user-theme@'; then
                    echo "  note: the User Themes extension is not enabled; the Shell theme only applies once it is."
                fi
            fi
            # libadwaita apps ignore the GTK theme and read only the user stylesheet
            la="$troot/$sc/libadwaita/gtk.css"; target="$cfg/gtk-4.0/gtk.css"
            if [ -f "$la" ]; then
                ac=$(current_accent "$sc")
                if [ -n "$ac" ] && [ "$ac" != "$acc_default" ]; then
                    accent_maps "$sc" "$ac"; tmpla=$(mktemp); trap 'rm -f "$tmpla"' EXIT
                    if [ "$map_light" = "$map_dark" ]; then sed -f "$map_dark" "$la" > "$tmpla"
                    else   # the light map applies before the @media (prefers-color-scheme: dark) block, the dark map from there on (tokens both variants share map differently)
                        awk -v h="$tmpla.h" -v t="$tmpla.t" '/^@media \(prefers-color-scheme: dark\)/ {d=1} {print > (d ? t : h)}' "$la"
                        { sed -f "$map_light" "$tmpla.h"; sed -f "$map_dark" "$tmpla.t"; } > "$tmpla"; rm -f "$tmpla.h" "$tmpla.t"
                    fi
                    chmod 644 "$tmpla"; la="$tmpla"
                fi
                mkdir -p "$(dirname "$target")"
                if [ ! -e "$target" ]; then cp "$la" "$target"; echo "Installed $target (libadwaita apps)."
                elif cmp -s "$la" "$target"; then echo "$target is already current."
                elif grep -q "libadwaita-gen.py" "$target" 2>/dev/null || [ -e "$target.bak" ]; then
                    # A file generated by candy-for-gnome earlier (another accent or scheme), or a backup of the original already exists
                    # (so this file was put here by these recipes): replace it without asking and keep the existing backup.
                    cp "$la" "$target"; echo "Updated $target (libadwaita apps)."
                elif [ -t 0 ]; then
                    read -r -p "$target differs from the scheme's libadwaita file. Replace it (the old one is kept as .bak)? [y/N] " a || a=n
                    case "$a" in [yY]*) cp -L --backup=numbered "$target" "$target.bak"; cp "$la" "$target"; echo "Replaced $target (old one: $target.bak)." ;; *) echo "Left $target alone." ;; esac
                else echo "$target differs from the scheme's libadwaita file; left alone (run in a terminal to replace it)."
                fi
            fi
            pty_cleanup; pty_switch "$sc"; gsv_switch "$sc"; gh_switch "$sc"; app_switch "$sc"; fp_check
            echo "Restart GTK apps to pick up the new theme."
        fi ;;

    *) echo "usage: themectl.sh <themes|icons> <install|list|update|remove|switch> [name] [accent]"; exit 2 ;;
esac
