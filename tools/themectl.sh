is_adwaita() { [ "${items_adw:-0}" = 1 ] && [ "$1" = Adwaita ]; }
is_installed() { is_adwaita "$1" && return 0; local f; while read -r f; do [ -e "$dest/$f" ] && is_ours "$dest/$f" "$(src_index "$1" "$f")" && return 0; done < <(folders_of "$1"); return 1; }
