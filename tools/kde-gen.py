"""Generate a scheme's KDE color schemes (<scheme>/kde/candy-for-gnome-<scheme>-{dark,light}.colors).

  python3 -I tools/kde-gen.py <scheme-dir> [--check]     # --check: print, write nothing

A KDE color scheme (KColorScheme; read by KDE and Kirigami apps, also the Flatpak ones, through ~/.config/kdeglobals and ~/.local/share/color-schemes). The
structure is the one KDE's own schemes have: [General] ColorScheme/Name, [KDE] contrast, [ColorEffects:Disabled|Inactive], [Colors:Button|Complementary|
Header|Header][Inactive]|Selection|Tooltip|View|Window] and [WM]. COLOURS: the roles of tools/appthemes.py qt_roles (the same ones the other generators use):
View = the editor background (bg_deep), Window and Header = bg, Button = surface_high (moved until the text has 4.5:1), Selection = the default accent with its
GTK ink, Tooltip = popover, foregrounds fg, inactive fg-dim, negative/neutral/positive = red/yellow/green and link/visited = blue/magenta of the editor
palette. ColorScheme and Name are the same word (the file's base name, candy-for-gnome-<scheme>-<variant>) so a lookup by either finds the file.
A dark-only scheme has only the dark file, a light-only one only the light file. The accent a user picked is applied by the installer (the default accent's
r,g,b is replaced); PILOT: featured schemes only (appthemes.QT_SCOPE = 'all' turns it on for every scheme). Marker: the first line `# candy-for-gnome: <scheme>`.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import appthemes as A

def csv(c): return ','.join(str(v) for v in A.sr.hx(c))

def colors(r, name, scheme, title, slot):
    acc, dim = r['accent'], r['dim']
    def grp(n, bgn, bga, fg, deco=None, neg=None, neu=None, pos=None):
        L = ['[%s]' % n, 'BackgroundAlternate=' + csv(bga), 'BackgroundNormal=' + csv(bgn), 'DecorationFocus=' + csv(deco or acc), 'DecorationHover=' + csv(deco or acc),
             'ForegroundActive=' + csv(acc), 'ForegroundInactive=' + csv(dim), 'ForegroundLink=' + csv(r['link']), 'ForegroundNegative=' + csv(neg or r['neg']),
             'ForegroundNeutral=' + csv(neu or r['neutral']), 'ForegroundNormal=' + csv(fg), 'ForegroundPositive=' + csv(pos or r['pos']),
             'ForegroundVisited=' + csv(r['visited']), '']
        return L
    t, win, view = r['text'], r['window'], r['view']
    L = ['# candy-for-gnome: %s' % scheme,
         '# SPDX-License-Identifier: MIT. Generated by tools/kde-gen.py from %s/scheme.toml; do not edit.' % scheme,
         '# %s, %s variant.' % (title, slot), '',
         '[General]', 'ColorScheme=' + name, 'Name=' + name, '', '[KDE]', 'contrast=4', '',
         '[ColorEffects:Disabled]', 'Color=' + csv(view), 'ColorAmount=0', 'ColorEffect=0', 'ContrastAmount=0.65', 'ContrastEffect=1', 'IntensityAmount=0.1', 'IntensityEffect=2', '',
         '[ColorEffects:Inactive]', 'ChangeSelectionColor=true', 'Color=' + csv(r['alt_window']), 'ColorAmount=0.025', 'ColorEffect=2', 'ContrastAmount=0.1',
         'ContrastEffect=2', 'Enable=false', 'IntensityAmount=0', 'IntensityEffect=0', '']
    L += grp('Colors:Button', r['button'], r['alt_window'], t)
    L += grp('Colors:Complementary', view, r['alt_view'], t)
    L += grp('Colors:Header', r['alt_window'], win, t)
    L += grp('Colors:Header][Inactive', win, r['alt_window'], t)
    L += grp('Colors:Selection', acc, r['alt_window'], r['accent_fg'], deco=acc, neg=r['accent_fg'], neu=r['accent_fg'], pos=r['accent_fg'])
    L += grp('Colors:Tooltip', r['tip'], win, t)
    L += grp('Colors:View', view, r['alt_view'], t)
    L += grp('Colors:Window', win, r['alt_window'], t)
    L += ['[WM]', 'activeBackground=' + csv(r['alt_window']), 'activeBlend=' + csv(t), 'activeForeground=' + csv(t),
          'inactiveBackground=' + csv(win), 'inactiveBlend=' + csv(dim), 'inactiveForeground=' + csv(dim)]
    return '\n'.join(L) + '\n'

def build(d):
    scheme, vs, S = A.model(d)
    out = {}
    if not A.in_qt_scope(scheme): return scheme, out    # pilot: featured schemes only (A.QT_SCOPE)
    for s, v in vs.items():
        n = A.ident(scheme, s); out[n + '.colors'] = colors(A.qt_roles(S, v), n, scheme, v.title, s)
    return scheme, out

if __name__ == '__main__': A.main(build, 'kde', __doc__)
