"""Generate a scheme's README.md (themes/<scheme>/README.md) from its scheme.toml.

  python3 -I tools/theme-readme-gen.py <scheme-dir> [--check]     # --check: print, write nothing

The page shows the committed palette pictures (palette-dark.svg and, where the scheme has a light variant, palette-light.svg, by relative link so GitHub
renders them), the title and credit, whether the scheme is dark-only or light-only, the default accent, the licence note and the two commands to install
and switch. Repository documentation only: the installer copies themes/<scheme>/gtk/<Name>/ and the per-tool files, never this page. Deterministic.
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)   # python3 -I does not add the script dir
import schemeroles as sr

def default_accent(scheme_dir):
    """(name, dark hex) of the default accent from accents/list (the line marked `default`)."""
    name = hexv = None
    try: lines = open(os.path.join(scheme_dir, 'accents', 'list')).read().splitlines()
    except OSError: return None
    for l in lines:
        f = l.split()
        if not f or f[0].startswith('#'): continue
        if name is None: name, hexv = f[0], f[1]
        if len(f) > 3 and f[3] == 'default': return f[0], f[1]
    return (name, hexv) if name else None

def build(scheme_dir):
    S, roles, _ = sr.load(scheme_dir)
    scheme = os.path.basename(os.path.abspath(scheme_dir))
    variants = [v for v in ('dark', 'light') if v in roles]
    kind = 'dark and light' if len(variants) == 2 else ('dark only' if variants == ['dark'] else 'light only')
    acc = default_accent(scheme_dir)
    L = ['# %s' % S['title'], '',
         '<!-- Generated by tools/theme-readme-gen.py from scheme.toml; do not edit. -->', '',
         'Terminal-inspired colors for GNOME (GTK 3, GTK 4 and libadwaita, GNOME Shell) and for terminals and command-line tools. Variants: %s.' % kind, '']
    for v in variants: L += ['![%s %s palette](palette-%s.svg)' % (S['title'], v, v), '']
    L += ['- Colors: %s.' % S.get('credit', 'see the repository NOTICE'),
          '- Default accent: %s%s; the other accents are listed by `switch-theme`.' % (acc[0], ' (%s)' % acc[1].upper() if acc else ''),
          '- Ptyxis uses its built-in palette `%s`%s.' % (S['ptyxis'], '' if 'ptyxis_light' not in S else ' (light: `%s`)' % S['ptyxis_light']),
          '', '## Install and use', '', '```',
          'ujust gnome-candy install-theme %s' % scheme, 'ujust gnome-candy switch-theme %s' % scheme, '```', '',
          'Without the image recipe, run `just install-theme %s` and `just switch-theme %s` in a checkout of [candy-for-gnome](https://github.com/redcodeworks/candy-for-gnome).' % (scheme, scheme), '',
          '## License', '',
          'The generated GTK and Shell files in `gtk/` derive from the stock GTK and GNOME Shell stylesheets and stay under the LGPL (each folder there has its `LICENSE`). '
          'The tooling and this page are MIT; the color credits are in the repository `NOTICE`.', '']
    return scheme, {'README.md': '\n'.join(L)}

def main():
    if len(sys.argv) < 2: sys.exit(__doc__)
    d = sys.argv[1].rstrip('/')
    scheme, files = build(d)
    if '--check' in sys.argv:
        for n, t in files.items(): print('== %s/%s' % (d, n)); print(t)
        return
    for n, t in files.items():
        with open('%s/%s' % (d, n), 'w') as f: f.write(t)
        print('wrote %s/%s' % (d, n))

if __name__ == '__main__': main()
