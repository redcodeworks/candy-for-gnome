#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Generate a scheme's Ghostty theme files (<scheme>/ghostty/) from its scheme.toml.

  python3 -I tools/ghostty-gen.py <scheme-dir> [--check]     # --check: print, write nothing

Files (all generated, never hand-edited):
  candy-for-gnome-<scheme>-dark, candy-for-gnome-<scheme>-light   a Ghostty theme (a plain Ghostty config file: background, foreground,
      cursor-color, cursor-text, selection-background, selection-foreground and `palette = N=#rrggbb` for N 0..15). A dark-only scheme
      has only the -dark file, a light-only one only the -light file (a dark theme labelled light would lie).
  <scheme>.conf   one line, `theme = dark:<dark file>,light:<light file>`; Ghostty follows the system appearance with this form. A dark-only
      scheme maps both appearances to its dark file (a light-only one to its light file), as Ptyxis does for such schemes.
Every file starts with the marker comment `# candy-for-gnome: <scheme>`, the installer's collision guard.

COLOURS come from the data the Ptyxis built-in decision uses (tools/schemeroles.py slot_colors): Background = bg_deep, Foreground = fg, Color1..6
the six accents, Color0/7/8..15 from [<variant>.terminal]. Where a variant lists a [<variant>.nudge] (the toolkit colour was moved off the Ptyxis
built-in for a contrast check) the terminal keeps the built-in value (`from`), because Ptyxis shows the built-in unchanged: so Ghostty shows what Ptyxis
shows. cursor-color = Foreground, cursor-text = Background, selection-background = the scheme's `selection` role, selection-foreground = Foreground
(Ptyxis has no values for these; they come from the scheme's own roles). A light variant without a Ptyxis built-in (no_builtin) uses the scheme's own
light values, where Ptyxis would show the dark built-in.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # python3 -I does not add the script dir
import schemeroles as sr

def ident(scheme, slot): return 'candy-for-gnome-%s-%s' % (scheme, slot)

def colors(S, roles, variant):
    """The 18 terminal colours of a variant as Ptyxis shows them: slot_colors, with every listed nudge reverted to the built-in value."""
    c = sr.slot_colors(S, roles, variant)
    for k, n in S[variant].get('nudge', {}).items():
        c[k] = n['from'].upper()
        if k == 'Foreground':
            T = S[variant].get('terminal', {})
            if 'cursor' not in T: c['Cursor'] = c['Foreground']
            if 'selection_text' not in T: c['SelectionForeground'] = c['Foreground']
    return c

def theme_text(scheme, S, roles, variant):
    c = colors(S, roles, variant)
    L = ['# candy-for-gnome: %s' % scheme,
         '# SPDX-License-Identifier: MIT. Generated by tools/ghostty-gen.py from %s/scheme.toml (rules in the script header); do not edit.' % scheme,
         '# %s, %s variant.' % (S['title'], variant),
         'background = %s' % c['Background'].lower(), 'foreground = %s' % c['Foreground'].lower(),
         'cursor-color = %s' % c['Cursor'].lower(), 'cursor-text = %s' % c['CursorText'].lower(),
         'selection-background = %s' % c['SelectionBackground'].lower(), 'selection-foreground = %s' % c['SelectionForeground'].lower()]
    L += ['palette = %d=%s' % (i, c['Color%d' % i].lower()) for i in range(16)]
    return '\n'.join(L) + '\n'

def build(scheme_dir):
    S, roles, _ = sr.load(scheme_dir)
    scheme = os.path.basename(os.path.abspath(scheme_dir))
    out = {}
    for slot in ('dark', 'light'):
        if slot in roles: out[ident(scheme, slot)] = theme_text(scheme, S, roles, slot)
    d = ident(scheme, 'dark' if 'dark' in roles else 'light'); l = ident(scheme, 'light' if 'light' in roles else 'dark')
    out[scheme + '.conf'] = '# candy-for-gnome: %s\ntheme = dark:%s,light:%s\n' % (scheme, d, l)
    return scheme, out

def main():
    if len(sys.argv) < 2: sys.exit(__doc__)
    d = sys.argv[1].rstrip('/')
    scheme, files = build(d)
    if '--check' in sys.argv:
        for n, t in files.items(): print('== ' + n); print(t)
        return
    os.makedirs(d + '/ghostty', exist_ok=True)
    for f in os.listdir(d + '/ghostty'): os.remove(os.path.join(d, 'ghostty', f))   # a scheme that lost a variant leaves no stale file
    for n, t in files.items():
        with open('%s/ghostty/%s' % (d, n), 'w') as f: f.write(t)
        print('wrote %s/ghostty/%s' % (d, n))

if __name__ == '__main__': main()
